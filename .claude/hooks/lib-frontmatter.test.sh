#!/bin/bash
# Доказательство мутацией для lib-frontmatter.sh.
#
# Мир с дефектом: YAML-комментарий читался как часть значения. Шаблоны фреймворка
# комментируют почти каждое поле — `accepted_until: ""  # ТРЕТИЙ ВИД КРАСНОГО…`,
# `max_lines: 300  # потолок файла`. Замер прогона: решение, заведённое из
# штатного `adr-template.md`, дало две ложных находки подряд — пустое поле
# сочлось заполненным, заполненное — пустым.

set -uo pipefail

LIB=${1:-"$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib-frontmatter.sh"}
[ -f "$LIB" ] || { printf 'нет библиотеки: %s\n' "$LIB" >&2; exit 1; }
# shellcheck source=/dev/null
. "$LIB"

EXPECTED_CASES=14
# shellcheck disable=SC2034
MUTATIONS=3
ran=0
failed=0
TRASH=()
cleanup() { [ ${#TRASH[@]} -eq 0 ] || rm -rf "${TRASH[@]}"; }
trap cleanup EXIT

doc() {  # строки шапки → путь к файлу
  local d f; d=$(mktemp -d); TRASH+=("$d"); f="$d/a.md"
  { printf -- '---\n'; printf '%s\n' "$@"; printf -- '---\n\n# Тело\n'; } > "$f"
  printf '%s' "$f"
}

check() {
  ran=$((ran + 1))
  if [ "$3" = "$2" ]; then printf 'PASS  %-52s ожидание «%s»\n' "$1" "$2"
  else printf 'FAIL  %-52s ожидание «%s», получено «%s»\n' "$1" "$2" "$3"; failed=$((failed + 1)); fi
}

# --- Значение в кавычках -----------------------------------------------------
F=$(doc 'name: "простое"')
check "значение в кавычках" "простое" "$(fm_field "$F" name)"

F=$(doc 'name: "ставка за м²"  # обязательно если решение выбирает инвариант')
check "комментарий после значения в кавычках отброшен" "ставка за м²" "$(fm_field "$F" name)"

F=$(doc 'name: ""        # ТРЕТИЙ ВИД КРАСНОГО. Заполняется, если решение принято')
check "пустое значение остаётся пустым" "" "$(fm_field "$F" name)"

# Решётка внутри кавычек — часть текста, а не начало комментария.
F=$(doc 'name: "порог #5 по счёту"')
check "решётка внутри кавычек — текст" "порог #5 по счёту" "$(fm_field "$F" name)"

F=$(doc "name: 'одинарные кавычки'  # комментарий")
check "одинарные кавычки тоже кавычки" "одинарные кавычки" "$(fm_field "$F" name)"

# --- Значение без кавычек ----------------------------------------------------
F=$(doc 'max_lines: 300')
check "число без кавычек" "300" "$(fm_field "$F" max_lines)"

F=$(doc 'max_lines: 300 # потолок файла; поднимается осознанно')
check "комментарий после числа отброшен" "300" "$(fm_field "$F" max_lines)"

F=$(doc 'phase: выбор площадки   # одна строка, не пересказ')
check "текст без кавычек с комментарием" "выбор площадки" "$(fm_field "$F" phase)"

# Пробел перед решёткой обязателен: слово с решёткой внутри — одно слово.
F=$(doc 'tag: версия#3')
check "решётка вплотную — часть значения" "версия#3" "$(fm_field "$F" tag)"

# --- Границы -----------------------------------------------------------------
F=$(doc 'name: "первое"' 'other: "второе"')
check "берётся своё поле, а не соседнее" "второе" "$(fm_field "$F" other)"

check "поля нет — пусто" "" "$(fm_field "$F" отсутствует)"

# Та же строка в теле документа настройкой не является: там она цитата или пример.
D=$(mktemp -d); TRASH+=("$D"); F="$D/b.md"
printf -- '---\nname: "из шапки"\n---\n\nВ теле: name: "из тела"\n' > "$F"
check "поле читается только из шапки" "из шапки" "$(fm_field "$F" name)"

# Файл без шапки вовсе — пусто, а не первая строка тела.
printf '# Просто документ\nname: "не шапка"\n' > "$F"
check "нет шапки — пусто" "" "$(fm_field "$F" name)"

check "файла нет — пусто" "" "$(fm_field "/nonexistent-fm-$$" name)"

if [ "$ran" -lt "$EXPECTED_CASES" ]; then
  printf 'FAIL  прогнано случаев %s из %s\n' "$ran" "$EXPECTED_CASES"
  failed=$((failed + 1))
fi
printf '\nбиблиотека: %s\n' "$LIB"
printf 'случаев: %s, провалено: %s\n' "$ran" "$failed"
[ "$failed" -eq 0 ]
