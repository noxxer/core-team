#!/bin/bash
# След работы: у построенного есть записанный замысел и запись сессии.
#
# ТИР: счёт — пропущенная запись не ломает следующую сессию, но копится
#
# Все гейты стоят на артефактах и потому слепы к отсутствию: файла нет — проверять
# нечего. Замер боевого прогона: пройден путь от идеи до снимков, написан код,
# сняты снимки — и ни одной записи в лентах работы, ни одной записи сессии.
# Прогон вёл тот, кто знает систему; короткий путь ничем не отмечен, и его
# выбирают именно потому, что он всегда доступен.
#
# Один предмет — «работа оставила след», два отказа:
#   1. код есть, а зачем он построен — нигде не записано;
#   2. работа шла (есть код или решения), а записей сессий нет.
#
# Ответ на вопрос «зачем построено» бывает записан двумя законными способами,
# и проверка знает оба. Через замысел идут, когда всё началось с идеи: она
# получает исход, из неё вырастает поставка, из поставки фичи. Через описание
# продукта идут, когда продукт пишется с нуля: сначала пути пользования и
# требования, потом дерево обещаний, потом код. Замер боевого прогона: работа
# шла вторым путём — два описанных пути, восемь требований, дерево из двадцати
# одного документа, — а проверка знала только первый и сообщала «построено без
# записанного зачем».
#
# Код ищется от корня проекта И от `code_path:` из шапки ledger. Раскладка
# «команда отдельно, код отдельно» встречается в трёх проектах из четырёх, и
# прибор, смотрящий только под корень, отвечал такому проекту «файлов кода нет —
# не измеряется», то есть молчал ровно там, где работа шла. Замер с мест
# (lotus-pro-team, 2026-09-09): `code_path` читал один прибор из четырёх, и
# ledger проекта нёс про это ручную пометку — человек заметил и починить не мог.
# Объявленный `code_path`, по которому каталога нет, — отказ, а не пропуск:
# указатель дороже пустой ячейки, потому что выглядит ответом.
#
# Что НЕ проверяется намеренно: проект без кода — исследование, документация,
# аналитика; там прибор молчит, потому что мерить нечего.
#
# ЗАПУСК: bash .claude/hooks/check-work-trail.sh [корень проекта]
#   exit 0 — след есть либо мерить нечего
#   exit 1 — построено без записанного замысла или без записи сессии,
#            либо `code_path` ведёт в никуда
#
# Доказательство мутацией: .claude/hooks/check-work-trail.test.sh

set -uo pipefail

ROOT=${1:-.}
PROJECT="${ROOT}/project"

[ -d "${PROJECT}" ] || { printf 'каталога project нет — проект ещё не заведён\n'; exit 0; }

# Код — файлы известных расширений вне служебных каталогов. Каталог снимков и
# зависимостей исключены: там чужое и производное.
count_code_in() {  # $1 = корень поиска
  find "$1" -type f \
    \( -name '*.py' -o -name '*.js' -o -name '*.mjs' -o -name '*.ts' -o -name '*.tsx' \
       -o -name '*.jsx' -o -name '*.go' -o -name '*.rs' -o -name '*.java' -o -name '*.rb' \
       -o -name '*.php' -o -name '*.vue' -o -name '*.svelte' \) \
    -not -path '*/.claude/*' -not -path '*/project/*' -not -path '*/node_modules/*' \
    -not -path '*/.git/*' -not -path '*/deck/output/*' -not -path '*/.trial/*' \
    2>/dev/null | wc -l | tr -d ' '
}

count_files_in() {  # $1 = каталог → число файлов, 0 если каталога нет
  [ -d "$1" ] || { printf '0'; return 0; }
  find "$1" -type f -name '*.md' 2>/dev/null | wc -l | tr -d ' '
}

# Второй корень поиска — репозиторий кода, объявленный в шапке ledger. Читается
# библиотекой шапки, чтобы комментарий после значения не стал частью пути.
_lib_fm="$(cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null && pwd)/lib-frontmatter.sh"
code_path=""
if [ -f "${_lib_fm}" ] && [ -f "${PROJECT}/ledger.md" ]; then
  # shellcheck source=/dev/null
  . "${_lib_fm}"
  code_path=$(fm_field "${PROJECT}/ledger.md" code_path)
fi
case "${code_path}" in ''|.|./) code_path="" ;; /*) ;; *) code_path="${ROOT}/${code_path}" ;; esac

code=$(count_code_in "${ROOT}")
code_path_dead=0
if [ -n "${code_path}" ]; then
  if [ -d "${code_path}" ]; then
    code=$((code + $(count_code_in "${code_path}")))
  else
    code_path_dead=1
  fi
fi
ideas=$(count_files_in "${PROJECT}/ideas")
deliveries=$(count_files_in "${PROJECT}/deliveries")
features=$(count_files_in "${PROJECT}/features")
sessions=$(count_files_in "${PROJECT}/sessions")
decisions=$(count_files_in "${PROJECT}/decisions")

# Второй законный путь: продукт описан раньше кода. Пути пользования живут либо
# в проекте, либо там, куда их кладёт инструмент дерева, — адрес спрашиваем
# у таблицы подключений и ищем по нему.
scenarios=$(count_files_in "${PROJECT}/scenarios")
_lib="$(cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null && pwd)/lib-points.sh"
POINTS=${CONNECTION_POINTS_FILE:-${PROJECT}/connection-points.md}
if [ "${scenarios}" -eq 0 ] && [ -f "${_lib}" ] && [ -f "${POINTS}" ]; then
  # shellcheck source=/dev/null
  . "${_lib}"
  where=$(point_location scenarios "${POINTS}")
  [ -n "${where}" ] && scenarios=$(count_files_in "${ROOT}/${where}")
fi

plan=$((ideas + deliveries + features + scenarios))

# Объявленный адрес кода, по которому ничего нет, — отказ ДО границы применимости:
# иначе проект с переехавшим репозиторием читался бы как «без кода» и молчал.
if [ "${code_path_dead}" -eq 1 ]; then
  printf 'КРАСНОЕ: code_path ведёт в никуда — ledger объявляет %s, каталога нет.\n' "${code_path}" >&2
  printf '  Приборы, ходящие по коду, меряют пустоту и отвечают «кода нет» вместо «код не здесь».\n' >&2
  printf '  Поправь `code_path:` в шапке project/ledger.md либо убери поле, если код лежит в корне.\n' >&2
  exit 1
fi

# Проект без кода прибор не трогает: исследованию, документации и аналитике
# мерить этим нечем, и молчание здесь — не пропуск, а граница применимости.
if [ "${code}" -eq 0 ]; then
  printf 'файлов кода нет — след работы этим прибором не измеряется\n'
  exit 0
fi

failures=0

if [ "${plan}" -eq 0 ]; then
  printf 'КРАСНОЕ: файлов кода %s, а зачем он построен — нигде не записано.\n' "${code}" >&2
  printf '  Ни замысла (ideas, deliveries, features), ни описанных путей пользования.\n' >&2
  printf '  Через месяц причину будет негде прочитать. Закрывается одной записью:\n' >&2
  printf '  `/plan-feat` заводит идею и её исход, `/spec` — путь пользования.\n' >&2
  failures=$((failures + 1))
fi

if [ "${sessions}" -eq 0 ] && { [ "${code}" -gt 0 ] || [ "${decisions}" -gt 0 ]; }; then
  printf 'КРАСНОЕ: работа шла (кода %s, решений %s), а записей сессий нет.\n' "${code}" "${decisions}" >&2
  printf '  Летопись пишется в конце сессии: без неё следующая начинается с нуля.\n' >&2
  failures=$((failures + 1))
fi

printf 'След работы: кода %s, замысел %s (из них путей пользования %s), сессий %s, решений %s.\n' \
  "${code}" "${plan}" "${scenarios}" "${sessions}" "${decisions}"
[ "${failures}" -eq 0 ] || { printf '\nпропусков следа: %s\n' "${failures}" >&2; exit 1; }
exit 0
