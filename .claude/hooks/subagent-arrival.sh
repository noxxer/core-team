#!/bin/bash
# Гард завершения роли: работа роли обязана доехать.
#
# Событие SubagentStop замерено на Claude Code 2.1.246 (проба 2026-08-26):
# приходит с `agent_type`, `last_assistant_message`, `agent_transcript_path`
# и `stop_hook_active`. Матчер по типу агента фильтрует верно.
#
# Две проверки над одним предметом — «доехала ли работа роли»:
#   1) ПАМЯТЬ: в отчёте есть раздел «Для памяти роли» (иначе память роли
#      не пополнится, и заметить это будет нечем — замер: 10 ролей из 22
#      с памятью старше их последней работы).
#   2) ПРИЁМКА: если бриф назвал файл приёмки, файл существует и непуст
#      (замер: три дорожки из шести потеряли работу целиком).
#
# ГРАНИЦЫ, названные сразу:
# - `facilitator` работает основной сессией, а не субагентом — под этот хук
#   он не попадает никогда. Его память приземляется по-прежнему вручную.
# - Хук НЕ дописывает память за роль. Он умеет только не дать роли уйти
#   молча. Приземление в `project/roles/<role>/context.md` остаётся за
#   оркестратором.
# - Неисправность самого гарда НЕ блокирует работу. Это осознанный отход от
#   fail-closed: гард стоит в пути КАЖДОГО прогона роли, и сломанный гард,
#   роняющий всё, дороже гарда, который что-то пропустил. Защита от поломки —
#   собственный набор тестов в CI, а не блокировка вслепую.
#
# Доказательство мутацией: .claude/hooks/subagent-arrival.test.sh
#
# Exit 0 — роль отпускается
# Exit 2 — роль не отпускается, текст уходит ей в контекст

set -uo pipefail

AGENTS_DIR=${AGENTS_DIR:-.claude/agents}
LANE_CHECK=${LANE_CHECK:-.claude/hooks/check-lane-acceptance.sh}

# Читаем встроенным перенаправлением: гард обязан пережить отсутствие PATH.
payload=$(</dev/stdin)

bail() { printf 'subagent-arrival: %s Роль отпущена без проверки.\n' "$1" >&2; exit 0; }

command -v jq >/dev/null 2>&1 || bail 'jq не найден.'
printf '%s' "${payload}" | jq -e 'type == "object"' >/dev/null 2>&1 || bail 'вход не разобран как объект.'

field() { printf '%s' "${payload}" | jq -r --arg k "$1" '.[$k] // empty' 2>/dev/null; }

role=$(field agent_type)
[ -n "${role}" ] || exit 0

# Роль фреймворка — та, у которой есть файл роли. Встроенные агенты
# (Explore, Plan, general-purpose) файла не имеют и под правило не подпадают:
# требовать от них блок памяти — ритуал. Заодно имя роли не попадает в путь
# непроверенным.
case "${role}" in *[!a-z0-9_-]*) exit 0 ;; esac
[ -f "${AGENTS_DIR}/${role}.md" ] || exit 0

# Повторный вход: блокируем один раз, иначе роль не выйдет никогда.
[ "$(field stop_hook_active)" = "true" ] && exit 0

findings=()

# --- 1. Блок памяти роли ----------------------------------------------------
# Ищем ЗАГОЛОВОК раздела, а не упоминание строки: роль, процитировавшая правило
# в тексте, блок памяти не вернула. Подстрочная проверка была бы ложно-зелёной.
report=$(field last_assistant_message)
if ! printf '%s\n' "${report}" | grep -qE '^[[:space:]]*[#*]*[[:space:]]*Для памяти роли'; then
  findings+=('в отчёте нет раздела «## Для памяти роли» — без него память роли не пополнится')
fi

# --- 2. Приёмка, названная в брифе ------------------------------------------
brief_acceptance() {  # $1 = стенограмма субагента; печатает путь или ничего
  jq -r 'select(.type == "user") | .message.content
         | if type == "array" then map(.text? // "") | join(" ") else . end' "$1" 2>/dev/null \
    | grep -m1 -oE 'ПРИЁМКА\.?[[:space:]]+[^[:space:]]+' \
    | awk '{print $NF}' | tr -d '`«»,'
}

transcript=$(field agent_transcript_path)
if [ -n "${transcript}" ] && [ -f "${transcript}" ]; then
  acceptance=$(brief_acceptance "${transcript}")
  if [ -n "${acceptance}" ] && [ -x "${LANE_CHECK}" ]; then
    if ! bash "${LANE_CHECK}" "${acceptance}" >/dev/null 2>&1; then
      findings+=("файл приёмки «${acceptance}», названный в брифе, не доехал — его нет или он пуст")
    fi
  fi
fi

[ "${#findings[@]}" -eq 0 ] && exit 0

{
  printf 'Работа роли %s не доехала полностью:\n' "${role}"
  printf '  — %s\n' "${findings[@]}"
  printf 'Допиши недостающее и заверши снова. Отчёт без блока памяти и приёмка без файла\n'
  printf 'исчезают вместе с твоим контекстом — восстановить их будет нечем.\n'
} >&2
exit 2
