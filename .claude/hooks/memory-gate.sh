#!/bin/bash
# Потребитель красноты памяти роли. Гард без потребителя есть мнение.
#
# ТИР: стоп — хук: блокирует правку на месте
#
# Замер (4 боевых проекта, 2026-08-26): семь файлов памяти выше предела чтения
# 256 КБ — dev 988 / 657 / 644 КБ, test 340, architect 320, guardian 285,
# facilitator 288. `dev` за пределом во ВСЕХ трёх проектах с разработкой.
# Числа 571.5 / 334.5 / 303.5 КБ, записанные в CLAUDE.md как повод завести
# check-role-memory.sh, сегодня равны 644 / 340 / 320: правило есть, проверщик
# написан, доказательство мутацией приложено — и все три файла с тех пор ВЫРОСЛИ.
# Потому что проверщик печатал в SessionStart без блокировки, а в /end-session
# его никто не был обязан слушать.
#
# Две работы над одним предметом «память роли пригодна к чтению»:
#   1) ПРИЧИНА — приземление лентой. Дописать датированный блок дешевле, чем
#      переписать раздел, поэтому лента побеждает состояние, если её пустить.
#      Отказ адресный: правка-дописывание с датированным заголовком.
#   2) НАКОПЛЕННОЕ — закрытие сессии. Запись сессии не проходит, пока
#      check-role-memory.sh краснеет. Это и есть «блокировать /end-session»:
#      блокируется не команда (она текст), а её продукт.
#
# ГРАНИЦЫ, названные сразу:
# - Хук НЕ переписывает память за роль и НЕ решает, что в ней состояние.
# - `Write` по памяти роли здесь не трогается: он закрыт `permissions.deny`
#   в развёрнутой копии (CLAUDE.md, «Неприкосновенные файлы»). Дублировать
#   запрет означало бы запереть единственный путь починки файла выше предела
#   чтения — его нельзя прочитать, значит нельзя и отредактировать точечно.
# - Неисправность самого гарда НЕ блокирует работу: хук стоит в пути каждой
#   правки, и сломанный гард, роняющий всё, дороже пропуска.
#
# Доказательство мутацией: .claude/hooks/memory-gate.test.sh
#
# Exit 0 — правка проходит
# Exit 2 — правка не проходит, текст уходит агенту в контекст

set -uo pipefail

MEMORY_CHECK=${MEMORY_CHECK:-.claude/hooks/check-role-memory.sh}
ROLES_DIR=${ROLES_DIR:-project/roles}

payload=$(</dev/stdin)

bail() { printf 'memory-gate: %s Правка пропущена без проверки.\n' "$1" >&2; exit 0; }

command -v jq >/dev/null 2>&1 || bail 'jq не найден.'
printf '%s' "${payload}" | jq -e 'type == "object"' >/dev/null 2>&1 || bail 'вход не разобран как объект.'

tool=$(printf '%s' "${payload}" | jq -r '.tool_name // empty' 2>/dev/null)
file=$(printf '%s' "${payload}" | jq -r '.tool_input.file_path // empty' 2>/dev/null)
[ -n "${tool}" ] && [ -n "${file}" ] || exit 0

# Предмет правки определяем один раз: ветки не должны перехватывать друг у друга
# управление. Ранний `exit 0` в первой ветке уводил из-под гарда правку уже
# существующей записи сессии — `Write` там бывает только в первый раз.
is_role_memory=false
case "${file}" in */roles/*/context.md|roles/*/context.md) is_role_memory=true ;; esac
is_session=false
case "${file}" in */sessions/*.md|sessions/*.md) is_session=true ;; esac

# --- 1. Причина: приземление памяти лентой -----------------------------------
if [ "${tool}" = "Edit" ] && [ "${is_role_memory}" = true ]; then
  old=$(printf '%s' "${payload}" | jq -r '.tool_input.old_string // empty' 2>/dev/null)
  new=$(printf '%s' "${payload}" | jq -r '.tool_input.new_string // empty' 2>/dev/null)

  # Пустой old_string — это создание содержимого, а не дописывание к нему.
  [ -n "${old}" ] || exit 0  # запись сессии этим путём не ходит: предмет другой

  # Дописывание: новое начинается со старого целиком. Перезапись раздела этой
  # формы не имеет — там старый текст ИСЧЕЗАЕТ, а не остаётся префиксом.
  # Кавычки вокруг ${old} делают глоб-символы в тексте буквальными.
  case "${new}" in
    "${old}"*) added=${new#"${old}"} ;;
    *) exit 0 ;;
  esac

  # Ищем ЗАГОЛОВОК с датой, а не дату в тексте: строка «решено 2026-08-26»
  # внутри состояния законна, отдельный датированный раздел — уже лента.
  printf '%s\n' "${added}" | grep -qE '^#{2,3} .*[0-9]{4}-[0-9]{2}-[0-9]{2}' || exit 0

  {
    printf 'Память роли — состояние, а не журнал. Эта правка дописывает датированный\n'
    printf 'раздел в %s, ничего не заменяя.\n\n' "${file}"
    printf 'Что сделать вместо этого:\n'
    printf '  — хронику дня записать в `project/sessions/` — её дом там;\n'
    printf '  — в память вернуть то, что ИСЧЕЗНЕТ, если не записать здесь, перезаписав\n'
    printf '    разделы: где роль стоит и почему · рабочее знание об этой системе ·\n'
    printf '    отвергнутые пути с причиной · своя повторяющаяся ошибка · открытые\n'
    printf '    вопросы · действующие DEC одной строкой · урок ремесла;\n'
    printf '  — закрывшиеся вопросы убрать, а не пометить закрытыми.\n\n'
    printf 'Чего в память НЕ кладут — у этого есть свой дом: состояние проекта (ledger) ·\n'
    printf 'события (sessions) · обоснование решений (decisions) · значения терминов\n'
    printf '(glossary, entities) · факты о мире (domain) · паттерн ремесла, верный в любом\n'
    printf 'проекте (DPF). Память роли хранит дорого купленное и нигде не оформленное.\n\n'
    printf 'Почему отказ: дописать дешевле, чем переписать, и у ленты нет дна. Так три\n'
    printf 'роли доросли до 988 / 657 / 644 КБ при пределе чтения 256 КБ — и работают\n'
    printf 'вслепую, потому что Read на таком файле отказывает молча.\n'
  } >&2
  exit 2
fi

# --- 2. Накопленное: запись сессии не проходит по красной памяти --------------
# И `Write`, и `Edit`: запись существующей сессии — тот же продукт /end-session.
if [ "${is_session}" = true ] && { [ "${tool}" = "Write" ] || [ "${tool}" = "Edit" ]; }; then
  [ -f "${MEMORY_CHECK}" ] || bail "проверщика памяти нет (${MEMORY_CHECK})."

  verdict=$(bash "${MEMORY_CHECK}" "${ROLES_DIR}" 2>&1) && exit 0

  {
    printf 'Сессию нельзя записать: память ролей не пригодна к чтению.\n\n'
    printf '%s\n\n' "${verdict}"
    printf 'Разбери память названных ролей и запиши сессию снова. Файл выше предела\n'
    printf 'чтения инструментом не открывается — разбирай его через Bash (`sed -n`,\n'
    printf '`awk`), хронику переноси в `project/sessions/`, в память возвращай срез.\n\n'
    printf 'Почему это блокирует: роль, не прочитавшая свою память, не падает — она\n'
    printf 'молча работает без неё. Закрытая сессия с красной памятью означает, что\n'
    printf 'следующая начнётся вслепую, и заметить это будет нечем.\n'
  } >&2
  exit 2
fi

exit 0
