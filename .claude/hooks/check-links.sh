#!/bin/bash
# Ссылки внутри поставки ведут в существующие файлы.
#
# ТИР: копия — про целостность поставки, а не про проект
#
# Переименование — самая частая правка документации и самая незаметная поломка:
# файл переехал, а десять текстов продолжают называть старый путь. Читатель идёт
# по указателю и не находит ничего; указатель дороже пустоты, потому что выглядит
# как ответ. Замер: за одну сессию переименованы понятие, лента и четыре команды —
# проверить это глазами нечем.
#
# Один предмет — «путь, названный в тексте, существует», три отказа:
#   1. ссылка на файл внутри `.claude/` или `plugins/`, которого нет;
#   2. ссылка на шаблон `templates/…`, которого нет;
#   3. разобрано ноль ссылок — половина «найдено не ноль».
#
# Что НЕ проверяется намеренно: пути в `project/` (рантайм потребителя, его ещё нет),
# внешние адреса, пути с подстановками (`<роль>`, `NNNN`, `*`) — это образцы формы.
#
# ЗАПУСК: bash .claude/hooks/check-links.sh [корень]
#   exit 0 — все разобранные ссылки ведут в существующие файлы
#   exit 1 — есть ссылка в никуда, либо разбирать оказалось нечего
#
# Доказательство мутацией: .claude/hooks/check-links.test.sh

set -uo pipefail

ROOT=${1:-.}
[ -d "${ROOT}/.claude" ] || { printf 'нет каталога .claude в %s — проверять нечего\n' "${ROOT}"; exit 1; }

failures=0
checked=0

# Ссылка — путь в обратных кавычках, начинающийся с `.claude/` или `plugins/`
# и оканчивающийся расширением файла. Пути с подстановками пропускаем: это форма.
while IFS=$'\t' read -r file link; do
  [ -n "${link}" ] || continue
  case "${link}" in
    *'<'*|*'>'*|*'*'*|*'NNN'*|*'NN.'*|*'{'*) continue ;;
  esac
  # Рантайм потребителя: файл появляется у него, а не в поставке. Опознаётся двумя
  # способами, и второй нужен потому, что `.gitignore` фреймворка НЕ приезжает при
  # наложении `.claude/` — замер на боевом прогоне: у потребителя два ложных красных.
  case "${link##*/}" in
    planner-context.md) continue ;;
  esac
  if [ -f "${ROOT}/.gitignore" ] && grep -qF "${link##*/}" "${ROOT}/.gitignore" 2>/dev/null; then
    continue
  fi
  checked=$((checked + 1))
  [ -e "${ROOT}/${link}" ] && continue
  printf 'КРАСНОЕ: %s называет %s — файла нет\n' "${file}" "${link}" >&2
  failures=$((failures + 1))
done < <(
  find "${ROOT}/.claude" "${ROOT}/plugins" -type f -name '*.md' 2>/dev/null | while IFS= read -r f; do
    # Два вида ссылок, и второй был невидим целиком.
    #
    # 1. Полный путь от корня: `.claude/...`, `plugins/...`.
    # 2. Путь БЕЗ префикса, начинающийся с каталога ядра: `knowledge/...`,
    #    `templates/...`, `hooks/...`. У такого база однозначна — это `.claude/`,
    #    поэтому проверять его можно без догадок. Замер: 81 такая ссылка, из них
    #    две вели в никуда, и одна — на `knowledge/stacks/`, каталог, которого не
    #    существует с выноса ремесла в плагин: команда конвейера водила роли по
    #    раскладке, которой нет, а роль в таком случае молча работает без справочника.
    #
    # `references/...` сюда НЕ входит намеренно: его база — корень навыка, а он
    # у каждого свой, и угадывание дало бы 24 ложных красных на живом дереве.
    grep -oE '`(\.claude|plugins)/[A-Za-z0-9_./-]+\.(md|sh|json)`' "$f" 2>/dev/null \
      | tr -d '`' | while IFS= read -r link; do
        printf '%s\t%s\n' "${f#"${ROOT}/"}" "${link}"
      done
    grep -oE '`(knowledge|templates|hooks|rules|output-styles|agents|commands|skills)/[A-Za-z0-9_./-]+\.(md|sh|json)`' "$f" 2>/dev/null \
      | tr -d '`' | while IFS= read -r link; do
        printf '%s\t%s\n' "${f#"${ROOT}/"}" ".claude/${link}"
      done
  done
)

# Половина «найдено не ноль»: файлы есть, а ссылок не разобрано — это отказ разбора.
if [ "${checked}" -eq 0 ]; then
  printf 'ОШИБКА: не разобрано ни одной ссылки — проверка прошла по пустому множеству.\n' >&2
  exit 1
fi

printf 'Ссылок проверено: %s.\n' "${checked}"
[ "${failures}" -eq 0 ] || { printf '\nссылок в никуда: %s\n' "${failures}" >&2; exit 1; }
exit 0
