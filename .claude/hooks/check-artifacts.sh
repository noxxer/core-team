#!/bin/bash
# У чего есть хозяин — живёт у хозяина. Остальное живёт в artifacts/ под потолком.
#
# ТИР: счёт — файл лежит не там; стоит минут, не ломает следующую сессию
#
# `artifacts/` — законное место для того, чего нет в шаблонах: заранее знать состав
# работы нельзя. Болезнь не в самом каталоге, а в том, что туда оседает работа,
# у которой дом уже есть.
#
# Замер (4 боевых проекта, 2026-08-26): 215 файлов, из них **19 имеют хозяина
# среди узлов** (FEAT/DEC/DR) и **59 — результаты сессий** (дата или номер сессии
# в имени). Каждый третий лежит не у себя дома. Зависимость обратная: 45 фич против
# 19 файлов в одном проекте, 10 фич против 123 в другом — каталог растёт не как
# дополнение к конвейеру, а как его замена.
#
# Один предмет — «артефакт лежит у себя дома и каталог остаётся обозримым».
# Три отказа:
#   1) ЕСТЬ ХОЗЯИН — имя называет FEAT/DEC/DR, а файл лежит в общей куче;
#   2) РЕЗУЛЬТАТ СЕССИИ — дата или номер сессии в имени: дом `project/sessions/`;
#   3) ПОТОЛОК — записей больше ёмкости из шапки `artifacts/README.md`.
#
# Способ смерти (`умирает:`) в шапке файла правилом ПОКА не является: требовать
# его сразу означало бы покраснеть на 137 унаследованных файлах, а прибор, который
# краснеет на всём, не читают. Форма объявлена в README и войдёт в проверку, когда
# наберётся замер.
#
# ЗАПУСК: bash .claude/hooks/check-artifacts.sh [каталог] [файл-README]
#   exit 0 — всё дома и каталог в пределах ёмкости (или каталога нет)
#   exit 1 — есть отказ, либо разобрать каталог не удалось
#
# Доказательство мутацией: .claude/hooks/check-artifacts.test.sh

set -uo pipefail

ARTIFACTS=${1:-${ARTIFACTS_DIR:-project/artifacts}}
INDEX=${2:-${ARTIFACTS_INDEX:-${ARTIFACTS}/README.md}}
DEFAULT_CEILING=${ARTIFACTS_CEILING:-40}

[ -d "${ARTIFACTS}" ] || { printf 'каталога артефактов нет (%s) — проверять нечего\n' "${ARTIFACTS}"; exit 0; }

ceiling="${DEFAULT_CEILING}"
if [ -f "${INDEX}" ]; then
  declared=$(awk 'NR==1 && $0!="---" {exit} NR==1 {next} /^---[[:space:]]*$/ {exit} {print}' "${INDEX}" \
             | grep -m1 -E '^ceiling:' | sed -E 's/^ceiling:[[:space:]]*//; s/[^0-9].*$//')
  case "${declared}" in ''|*[!0-9]*) ;; *) ceiling="${declared}" ;; esac
fi

join_list() { printf '%s, ' "$@" | sed 's/, $//'; }

owned=()
session_results=()
counted=0

while IFS= read -r name; do
  [ -n "${name}" ] || continue
  case "${name}" in
    .*|README.md|archive) continue ;;   # архив и оглавление в счёт не идут
  esac
  counted=$((counted + 1))

  # Хозяин важнее даты: файл `dec137-...-2026-07-27.md` едет к решению, а не в сессии.
  if printf '%s' "${name}" | grep -qiE '(^|[^a-z])(feat|dec|dr)-?[0-9]{2,}'; then
    owned+=("${name}")
  elif printf '%s' "${name}" | grep -qE '[0-9]{4}-[0-9]{2}-[0-9]{2}|-[0-9]{3}(\.md)?$'; then
    session_results+=("${name}")
  fi
done < <(ls -1 "${ARTIFACTS}" 2>/dev/null)

printf 'Артефакты %s: записей %s при ёмкости %s.\n' "${ARTIFACTS}" "${counted}" "${ceiling}"

# Половина «найдено не ноль» стоит на РАЗБОРЕ: каталог есть, а записей ноль —
# законный новый проект; но каталог, который не удалось перечислить, — отказ.
if [ "${counted}" -eq 0 ] && [ -z "$(ls -A "${ARTIFACTS}" 2>/dev/null)" ]; then
  printf 'Каталог пуст — команда ещё ничего не заводила.\n'
  exit 0
fi

failed=0

if [ ${#owned[@]} -gt 0 ]; then
  printf '\nУ ЭТИХ ЕСТЬ ХОЗЯИН (%s): %s.\n' "${#owned[@]}" "$(join_list "${owned[@]}")" >&2
  printf 'Имя называет фичу, решение или запись дрейфа — значит дом уже есть:\n' >&2
  printf '`features/FEAT-NNNN-<slug>/`, файл решения, строка реестра дрейфа. Половина\n' >&2
  printf 'найдётся, половина нет — ровно так работа про один предмет перестаёт быть целой.\n' >&2
  failed=1
fi

if [ ${#session_results[@]} -gt 0 ]; then
  printf '\nЭТО РЕЗУЛЬТАТЫ СЕССИЙ (%s): %s.\n' "${#session_results[@]}" "$(join_list "${session_results[@]}")" >&2
  printf 'Дата или номер сессии в имени означает: артефакт умирает прочтением. Его дом —\n' >&2
  printf '`project/sessions/<id>/`, там у него ротация. В общей куче он остаётся навсегда\n' >&2
  printf 'и через месяц неотличим от живого справочника.\n' >&2
  failed=1
fi

if [ "${counted}" -gt "${ceiling}" ]; then
  printf '\nПОТОЛОК ПРОБИТ: записей %s при ёмкости %s.\n' "${counted}" "${ceiling}" >&2
  printf 'Одно из трёх, явно: разнести по домам то, у чего дом есть · увезти отработанное\n' >&2
  printf 'в `artifacts/archive/` · поднять `ceiling:` в шапке README с причиной. Замер: в\n' >&2
  printf 'каталоге на 123 файла искать перестают и заводят то же самое заново.\n' >&2
  failed=1
fi

[ "${failed}" -eq 0 ] || exit 1
exit 0
