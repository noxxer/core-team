#!/bin/bash
# Точки подключения: ядро держит правила, плагины держат инструменты.
#
# ТИР: стоп — роль, считающая инструмент подключённым, работает без него молча
#
# Точка подключения — ОБЯЗАТЕЛЬСТВО слоя работы (нумерованные требования,
# контракты модулей, доказательство прохождения сценария), которое закрывает
# инструмент. Ядро не знает имён плагинов: оно объявляет точки, а плагин
# объявляет, что закрывает. Не закрыта — деградирует ВСЛУХ, а не молчит.
#
# Один предмет — «точка либо закрыта работающим инструментом, либо деградирует
# вслух», четыре отказа:
#   1. закрыта плагином, которого НЕТ среди установленных;
#   2. закрыта плагином, который установлен, но ВЫКЛЮЧЕН (то же молчание);
#   3. не закрыта, и деградация не объявлена — дыра без имени;
#   4. точка, объявленная ядром, в проекте отсутствует вовсе.
#
# Замер: у Founder-а шесть плагинов i-m-senior-developer стоят в project-scope
# и все ВЫКЛЮЧЕНЫ. «Установлен» и «работает» — разные утверждения, и различить
# их глазами в таблице проекта нечем.
#
# ЗАПУСК: bash .claude/hooks/check-connection-points.sh [файл-точек] [канон-ядра]
#   exit 0 — все точки закрыты работающим инструментом либо деградируют вслух
#   exit 1 — есть точка, о которой проект думает неправду
#
# Список установленного берётся командой из PLUGIN_LIST_CMD (умолчание
# `claude plugin list`) — зависимость сделана явной, иначе прибор непроверяем.
# Списка нет (среда без CLI) — проверка ФОРМЫ идёт, проверка ЗАКРЫТИЯ
# называется несделанной. Зелёное, полученное взглядом в пустоту, — не зелёное.
#
# Доказательство мутацией: .claude/hooks/check-connection-points.test.sh

set -uo pipefail

POINTS=${1:-${CONNECTION_POINTS_FILE:-project/connection-points.md}}
CANON=${2:-${CONNECTION_POINTS_CANON:-.claude/knowledge/connection-points.md}}
PLUGIN_LIST_CMD=${PLUGIN_LIST_CMD:-claude plugin list}

[ -f "${POINTS}" ] || { printf 'файла точек нет (%s) — проект их ещё не заполнял\n' "${POINTS}"; exit 0; }

# Строки таблицы точек: `| `точка` | обязательство | чем закрыта | источник | деградация |`.
# Имя точки в обратных кавычках — иначе строка-пример из прозы попадёт в счёт.
table_rows() {
  grep -E '^\|[[:space:]]*`[a-z][a-z0-9:-]*`[[:space:]]*\|' "$1" || true
}

field() {  # $1 = строка таблицы, $2 = номер колонки
  printf '%s\n' "$1" | awk -F'|' -v n="$2" '{gsub(/^[[:space:]]+|[[:space:]]+$/, "", $(n+1)); print $(n+1)}'
}

unquote() { printf '%s' "$1" | tr -d '`*'; }

is_empty() {  # прочерк и пустая ячейка — одно и то же: не сказано ничего
  case "$(printf '%s' "$1" | tr -d '[:space:]')" in
    ''|'—'|'-'|'–'|'?'|'…') return 0 ;;
    *) return 1 ;;
  esac
}

rows=$(table_rows "${POINTS}")

# Половина «найдено не ноль»: файл заведён, а разобрано ноль точек — это отказ
# разбора, а не проект без точек. Молчаливый ноль читается как «всё закрыто».
if [ -z "${rows}" ]; then
  printf 'ОШИБКА: в %s не разобрано ни одной точки подключения.\n' "${POINTS}" >&2
  printf 'Точка записывается строкой таблицы, её имя — в обратных кавычках.\n' >&2
  exit 1
fi

# «Список получить нечем» и «плагинов ноль» — разные утверждения, и различает их
# КОД ВОЗВРАТА, а не пустота вывода. Иначе среда без CLI и чистая машина
# неотличимы, и прибор молча зеленеет там, где не измерял.
have_list=yes
installed=$(${PLUGIN_LIST_CMD} 2>/dev/null) || have_list=no

# Плагин считается закрывающим точку, только если он ВКЛЮЧЁН: `claude plugin list`
# печатает имя строкой `❯ имя@маркетплейс`, а состояние — отдельной строкой ниже.
plugin_state() {  # $1 = имя плагина → enabled | disabled | absent
  printf '%s\n' "${installed}" | awk -v want="$1" '
    $0 ~ /^[[:space:]]*[^[:space:]]+[[:space:]]+[A-Za-z0-9_-]+@/ {
      name = $0
      sub(/^[^A-Za-z0-9_-]*/, "", name)
      sub(/@.*$/, "", name)
      inside = (name == want)
      next
    }
    inside && /Status:/ {
      print ($0 ~ /enabled/) ? "enabled" : "disabled"
      exit
    }
  ' | head -1
}

failures=0
checked=0
declare -a NAMES=()

while IFS= read -r row; do
  [ -n "${row}" ] || continue
  name=$(unquote "$(field "${row}" 1)")
  closed_by=$(field "${row}" 3)
  degradation=$(field "${row}" 5)
  [ -n "${name}" ] || continue
  checked=$((checked + 1))
  NAMES+=("${name}")

  if is_empty "${closed_by}"; then
    if is_empty "${degradation}"; then
      printf 'КРАСНОЕ: точка `%s` не закрыта, и деградация не объявлена.\n' "${name}" >&2
      printf '  Дыра без имени неотличима от закрытой точки — назови, как работаем без инструмента.\n' >&2
      failures=$((failures + 1))
    fi
    continue
  fi

  plugin=$(unquote "${closed_by}")
  plugin=${plugin%%@*}
  # «ядро» — законный закрыватель: точка закрыта средствами самого фреймворка.
  case "${plugin}" in ядро|core|ядра) continue ;; esac

  [ "${have_list}" = yes ] || continue

  case "$(plugin_state "${plugin}")" in
    enabled) ;;
    disabled)
      printf 'КРАСНОЕ: точка `%s` закрыта плагином `%s`, а он ВЫКЛЮЧЕН.\n' "${name}" "${plugin}" >&2
      printf '  Установлен — не то же самое, что работает: роль зовёт навык, которого в сессии нет.\n' >&2
      failures=$((failures + 1))
      ;;
    *)
      printf 'КРАСНОЕ: точка `%s` закрыта плагином `%s`, а он НЕ УСТАНОВЛЕН.\n' "${name}" "${plugin}" >&2
      printf '  Поставить: claude plugin install %s --scope project — либо объявить деградацию.\n' "${plugin}" >&2
      failures=$((failures + 1))
      ;;
  esac
done <<< "${rows}"

# Сверка с каноном ядра: непустота сторон прежде равенства. Пустой канон
# превратил бы сверку в тождество и дал бы зелёное на любом проекте.
if [ -f "${CANON}" ]; then
  # printf без перевода строки склеил бы имена в одно — имя точки обязано быть строкой.
  canon_names=$(table_rows "${CANON}" | while IFS= read -r r; do printf '%s\n' "$(unquote "$(field "${r}" 1)")"; done)
  if [ -z "${canon_names}" ]; then
    printf 'ОШИБКА: канон %s не дал ни одной точки — сверять не с чем.\n' "${CANON}" >&2
    exit 1
  fi
  while IFS= read -r want; do
    [ -n "${want}" ] || continue
    found=no
    for have in "${NAMES[@]}"; do [ "${have}" = "${want}" ] && { found=yes; break; }; done
    if [ "${found}" = no ]; then
      printf 'КРАСНОЕ: точка `%s` объявлена ядром, а в проекте её нет.\n' "${want}" >&2
      printf '  Слой работы, о котором проект не сказал ничего, не деградирует — он невидим.\n' >&2
      failures=$((failures + 1))
    fi
  done <<< "${canon_names}"
fi

printf 'Точек подключения разобрано: %s.\n' "${checked}"
if [ "${have_list}" = no ]; then
  printf 'ЗАКРЫТИЕ НЕ СВЕРЕНО: список плагинов получить нечем (%s).\n' "${PLUGIN_LIST_CMD}" >&2
  printf '  Проверена только форма записи. Это не «всё в порядке», это «не измерено».\n' >&2
fi
[ "${failures}" -eq 0 ] || { printf '\nточек, о которых проект думает неправду: %s\n' "${failures}" >&2; exit 1; }
exit 0
