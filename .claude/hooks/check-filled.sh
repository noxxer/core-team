#!/bin/bash
# Заполненность: артефакт несёт содержание, а не остался шаблоном.
#
# ТИР: стоп — пустой ledger ломает следующую сессию: она стартует без «где мы»
#
# Все приборы фреймворка выросли из боевых проектов, где содержание уже было.
# Они умеют говорить «этого стало слишком много» — хроника в поле, реестр выше
# потолка, память выше предела чтения — и молчат, когда содержания нет вовсе.
# Замер боевого прогона: пройден весь путь до снимков, `ledger.md` остался
# шаблоном с подсказками в квадратных скобках, `check-ledger.sh` зелёный.
#
# Один предмет — «обязательный артефакт заполнен», четыре отказа:
#   1. подсказка шаблона осталась на месте (`[текст]`, `<роль>`, `YYYY-MM-DD`);
#   2. файл не отличается от своего шаблона — его скопировали и не тронули;
#   3. обязательного артефакта нет вовсе;
#   4. осмотрено ноль артефактов — половина «найдено не ноль».
#
# Два признака нужны, потому что каждый ловит своё. Подсказка в скобках ловит
# частично заполненный файл; сравнение с шаблоном — нетронутый, где подсказок нет
# вовсе. Замер: `values.md` и `glossary.md` прошли первый признак и оба остались
# шаблонами.
#
# Что НЕ считается подсказкой: ссылка `[текст](адрес)` · всё внутри HTML-коммен-
# тария — там законно живут образцы формы (см. `templates/project/requirements.md`,
# где образцы вынесены в комментарий именно ради приборов).
#
# ЗАПУСК: bash .claude/hooks/check-filled.sh [каталог project]
#   exit 0 — все обязательные артефакты заполнены (или проекта ещё нет)
#   exit 1 — есть артефакт, оставшийся шаблоном
#
# Доказательство мутацией: .claude/hooks/check-filled.test.sh

set -uo pipefail

PROJECT=${1:-${PROJECT_DIR:-project}}

[ -d "${PROJECT}" ] || { printf 'каталога %s нет — проект ещё не заведён\n' "${PROJECT}"; exit 0; }

# Обязательные к заполнению: те, что читает роль в начале работы. Список закрытый —
# артефакт, заводимый по мере надобности, пустым быть вправе.
REQUIRED=(ledger.md values.md glossary.md domain.md)
OPTIONAL=(passport.md claims.md design-system.md)

# Строка-подсказка опознаётся сравнением с шаблоном, а не догадкой о смысле.
# Подсказка — это строка, которая ЕСТЬ В ШАБЛОНЕ и осталась в файле дословно.
# Текстовые признаки пробовали и отвергли: `[низкий]`, `[закрыт → DEC-019]` —
# данные, а `[название блока]` — подсказка, и по форме они неразличимы.
# Сравнение с источником даёт ноль ложных срабатываний на любых данных.
TEMPLATES=${TEMPLATES_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../templates/project" 2>/dev/null && pwd)}

template_for() {  # $1 = имя артефакта → путь шаблона или пусто
  local name=$1
  case "${name}" in
    ledger.md|values.md|glossary.md|domain.md|claims.md|design-system.md) : ;;
    passport.md) name="product-passport.md" ;;
    *) : ;;
  esac
  [ -n "${TEMPLATES}" ] && [ -f "${TEMPLATES}/${name}" ] && printf '%s' "${TEMPLATES}/${name}"
}

# Число строк-подсказок шаблона, оставшихся в файле, и первая из них.
hints_in() {  # $1 = файл, $2 = шаблон → «число<TAB>строка»
  awk '
    NR == FNR {
      # Строка шаблона считается подсказкой, если несёт `[...]`, `YYYY-MM-DD`
      # или `role_name`. Комментарии шаблона пропускаем: там образцы формы.
      if (/<!--/) in_comment = 1
      if (in_comment) { if (/-->/) in_comment = 0; next }
      line = $0
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", line)
      if (line == "") next
      # Чекбокс `- [ ]` — задача из шаблона, её отмечают, а не заполняют.
      # Замер: чеклист первых шагов в ledger краснел как незаполненная подсказка.
      if (line ~ /^-[[:space:]]*\[[ xX]?\]/) next
      if (line ~ /\[[^]]+\]/ || line ~ /YYYY-MM-DD/ || line ~ /role_name/) hint[line] = 1
      next
    }
    {
      probe = $0
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", probe)
      if (probe != "" && (probe in hint)) {
        total++
        if (first == "") first = FNR ": " substr(probe, 1, 90)
      }
    }
    END { printf "%d\t%s\n", total + 0, first }
  ' "$2" "$1"
}

# Второй признак: файл не отличается от шаблона — его скопировали и не тронули.
# Нужен потому, что первый ловит только оставшиеся подсказки: артефакт без единой
# подсказки в шаблоне (словарь, ценности) прошёл бы первую проверку пустым.
# Дата и имя роли из сравнения убраны: их правит копирование, а не человек.
diff_from_template() {  # $1 = имя, $2 = файл → число своих строк или «-»
  local tpl
  tpl=$(template_for "$1")
  [ -n "${tpl}" ] || { printf '-'; return 0; }
  diff <(sed -E 's/[0-9]{4}-[0-9]{2}-[0-9]{2}//g; s/role_name//g' "$2") \
       <(sed -E 's/[0-9]{4}-[0-9]{2}-[0-9]{2}//g; s/role_name//g' "${tpl}") 2>/dev/null \
    | grep -c '^[<>]' || true
}

# Порог ровно один: НОЛЬ отличий значит «скопировали и не тронули». Любая правка
# даёт минимум одну строку разницы. Порог выше был хрупок: файл, где заменили одну
# строку, считался нетронутым.
MIN_DIFF=1

failures=0
checked=0

for name in "${REQUIRED[@]}"; do
  file="${PROJECT}/${name}"
  if [ ! -f "${file}" ]; then
    printf 'КРАСНОЕ: обязательного артефакта %s нет — роль начнёт работу без него.\n' "${name}" >&2
    failures=$((failures + 1))
    continue
  fi
  checked=$((checked + 1))
  tpl=$(template_for "${name}")
  if [ -z "${tpl}" ]; then
    printf 'НЕ СВЕРЕНО: для %s нет шаблона — заполненность не измерена.\n' "${name}" >&2
    continue
  fi
  IFS=$'\t' read -r hints where <<< "$(hints_in "${file}" "${tpl}")"
  if [ "${hints}" -gt 0 ]; then
    printf 'КРАСНОЕ: %s остался шаблоном — подсказок не заполнено: %s.\n' "${name}" "${hints}" >&2
    printf '  Первая: %s\n' "${where}" >&2
    failures=$((failures + 1))
    continue
  fi
  changed=$(diff_from_template "${name}" "${file}")
  if [ "${changed}" != "-" ] && [ "${changed}" -lt "${MIN_DIFF}" ]; then
    printf 'КРАСНОЕ: %s не отличается от шаблона — строк своих: %s.\n' "${name}" "${changed}" >&2
    printf '  Файл скопировали и не тронули: роль прочитает форму вместо содержания.\n' >&2
    failures=$((failures + 1))
  fi
done

# Необязательные осматриваются, только если заведены: их отсутствие законно.
for name in "${OPTIONAL[@]}"; do
  file="${PROJECT}/${name}"
  [ -f "${file}" ] || continue
  checked=$((checked + 1))
  tpl=$(template_for "${name}")
  [ -n "${tpl}" ] || continue
  IFS=$'\t' read -r hints where <<< "$(hints_in "${file}" "${tpl}")"
  if [ "${hints}" -gt 0 ]; then
    printf 'КРАСНОЕ: %s заведён, но остался шаблоном — подсказок: %s.\n' "${name}" "${hints}" >&2
    printf '  Первая: %s\n' "${where}" >&2
    failures=$((failures + 1))
  fi
done

# Половина «найдено не ноль»: каталог есть, а осматривать оказалось нечего —
# это отказ разбора, а не здоровый проект.
if [ "${checked}" -eq 0 ]; then
  printf 'ОШИБКА: в %s не осмотрено ни одного артефакта.\n' "${PROJECT}" >&2
  exit 1
fi

printf 'Артефактов осмотрено: %s.\n' "${checked}"
[ "${failures}" -eq 0 ] || { printf '\nартефактов, оставшихся шаблоном: %s\n' "${failures}" >&2; exit 1; }
exit 0
