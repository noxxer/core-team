#!/bin/bash
# Требование пригодно к исполнению: у него есть источник, исполнитель и проверка.
#
# ТИР: счёт — обязательство не взято; копится, но не рушится
#
# Замер (боевой проект, 2026-08-26): в реестре рисков 18 записей, из них Legal 11
# и Security 5 — согласие пользователя, оферта, трансграничная передача ПД,
# админ-эндпоинты без аудит-лога. Все закрываются постройкой, то есть это
# обязательства, а не риски. Записанные под чужим именем, они стали невидимы:
# у риска нет исполнителя, его никто не берёт на себя. Founder называл три из них
# по памяти как «требования, которых в проекте нет» — а они лежали в файле.
#
# Механическая причина смешения была в форме: запись риска содержала поле
# «Требование закона / стандарта». Обязательству дали слот внутри риска.
#
# Один предмет — «требование можно исполнить и проверить». Три его отказа:
#   1) НЕТ ИСТОЧНИКА — без «откуда обязаны» это пожелание, и его дом backlog;
#   2) ЗАЯВЛЕНО ПОКРЫТИЕ БЕЗ ПРОВЕРКИ — статус говорит «покрыто», проверять нечем;
#   3) ОЧЕРЕДЬ НЕ ВЗЯТЫХ ВЫШЕ ЁМКОСТИ — обязательства копятся без исполнителя.
#
# Ёмкость очереди берётся из шапки файла (`unassigned_ceiling:`), а не отсюда:
# сколько обязательств проект вправе держать не взятыми — свойство проекта.
#
# ЗАПУСК: bash .claude/hooks/check-requirements.sh [файл-требований]
#   exit 0 — требования исполнимы (или файла нет)
#   exit 1 — есть отказ, либо разобрать файл не удалось
#
# Доказательство мутацией: .claude/hooks/check-requirements.test.sh

set -uo pipefail

REQUIREMENTS=${1:-${REQUIREMENTS_FILE:-project/requirements.md}}
SECTION=${REQUIREMENTS_SECTION:-Действующие требования}

[ -f "${REQUIREMENTS}" ] || { printf 'файла требований нет (%s) — проверять нечего\n' "${REQUIREMENTS}"; exit 0; }

# Ёмкость очереди читаем ТОЛЬКО из шапки: число в теле — текст, а не настройка.
ceiling=$(awk 'NR==1 && $0!="---" {exit} NR==1 {next} /^---[[:space:]]*$/ {exit} {print}' "${REQUIREMENTS}" \
          | grep -m1 -E '^unassigned_ceiling:' | sed -E 's/^unassigned_ceiling:[[:space:]]*//; s/[^0-9].*$//')
case "${ceiling}" in ''|*[!0-9]*) ceiling=5 ;; esac

# Половина «найдено не ноль» стоит на РАЗБОРЕ, а не на количестве: ноль требований
# у нового проекта законен, а отсутствие раздела означает, что мерить нечем.
if ! grep -qE "^## ${SECTION}" "${REQUIREMENTS}"; then
  printf 'ОШИБКА: в %s нет раздела «%s» — разобрать требования нечем.\n' "${REQUIREMENTS}" "${SECTION}" >&2
  printf 'Имя раздела — контракт с этим прибором: переименовали, и он ослеп.\n' >&2
  exit 1
fi

is_placeholder() {  # $1 = значение ячейки
  case "$1" in
    ''|'-'|'—'|'TBD'|'tbd'|'n/a') return 0 ;;
    \<*|*\>) return 0 ;;
    *) return 1 ;;
  esac
}

join_list() { printf '%s, ' "$@" | sed 's/, $//'; }

trim() { printf '%s' "$1" | sed -E 's/^[[:space:]]*//; s/[[:space:]]*$//; s/^\*+//; s/\*+$//; s/`//g'; }

examined=0
no_source=()
claimed_unverified=()
unassigned=()

while IFS= read -r row; do
  id=$(trim "$(printf '%s' "${row}" | cut -d'|' -f2)")
  source=$(trim "$(printf '%s' "${row}" | cut -d'|' -f4)")
  owner=$(trim "$(printf '%s' "${row}" | cut -d'|' -f5)")
  verify=$(trim "$(printf '%s' "${row}" | cut -d'|' -f6)")
  status=$(trim "$(printf '%s' "${row}" | cut -d'|' -f7)")
  examined=$((examined + 1))

  is_placeholder "${source}" && no_source+=("${id}")
  is_placeholder "${owner}" && unassigned+=("${id}")

  # «Покрыто» без адреса проверки — заявление, а не покрытие. Ровно этот класс
  # делает зелёные отчёты при неработающем прод-пути (CHK-WIRE).
  case "${status}" in
    *покрыт*|*машин*) is_placeholder "${verify}" && claimed_unverified+=("${id}") ;;
  esac
done < <(awk -v want="## ${SECTION}" '
  # Строка внутри HTML-комментария записью не является: там живут образцы формы
  # и временно снятые требования. Иначе прибор краснеет на собственном шаблоне.
  /<!--/ {commented=1}
  commented {if (/-->/) commented=0; next}
  $0 == want {inside=1; next}
  /^## / {inside=0}
  inside && /^\|[[:space:]]*\**(FR|NFR)-[0-9]+/ {print}
' "${REQUIREMENTS}")

printf 'Требования %s: разобрано %s, ёмкость очереди не взятых %s.\n' \
  "${REQUIREMENTS}" "${examined}" "${ceiling}"

if [ "${examined}" -eq 0 ]; then
  printf 'Записей ноль. Либо обязательства не записывали, либо у проекта их нет —\n'
  printf 'второе бывает редко: закон, оферта и договор действуют без нашего согласия.\n'
  exit 0
fi

failed=0

if [ ${#no_source[@]} -gt 0 ]; then
  printf '\nНЕТ ИСТОЧНИКА ОБЯЗАТЕЛЬСТВА (%s): %s.\n' "${#no_source[@]}" "$(join_list "${no_source[@]}")" >&2
  printf 'Без «откуда обязаны» это пожелание, а не требование: его нечем защитить в споре\n' >&2
  printf 'о приоритете. Назови норму, пункт оферты, договор или решение — либо увези в backlog.\n' >&2
  failed=1
fi

if [ ${#claimed_unverified[@]} -gt 0 ]; then
  printf '\nПОКРЫТИЕ ЗАЯВЛЕНО БЕЗ ПРОВЕРКИ (%s): %s.\n' "${#claimed_unverified[@]}" "$(join_list "${claimed_unverified[@]}")" >&2
  printf 'Статус говорит «покрыто», а адреса проверки нет. Зелёный отчёт без прод-пути —\n' >&2
  printf 'тот же класс, что CHK-WIRE: заявление о покрытии покрытием не является.\n' >&2
  failed=1
fi

if [ ${#unassigned[@]} -gt "${ceiling}" ]; then
  printf '\nОЧЕРЕДЬ НЕ ВЗЯТЫХ ВЫШЕ ЁМКОСТИ: %s при ёмкости %s.\n' "${#unassigned[@]}" "${ceiling}" >&2
  printf 'Не взятые: %s.\n' "$(join_list "${unassigned[@]}")" >&2
  printf 'Обязательство без исполнителя не исполняется само. Одно из двух, явно:\n' >&2
  printf '  1) назвать исполнителя — модуль, фичу или роль, которая СДАЁТ работу;\n' >&2
  printf '  2) поднять `unassigned_ceiling:` в шапке с причиной — осознанно, а не молча.\n' >&2
  failed=1
elif [ ${#unassigned[@]} -gt 0 ]; then
  printf 'Не взяты (%s из %s допустимых): %s.\n' \
    "${#unassigned[@]}" "${ceiling}" "$(join_list "${unassigned[@]}")"
fi

[ "${failed}" -eq 0 ] || exit 1
exit 0
