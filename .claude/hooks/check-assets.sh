#!/bin/bash
# Актив остаётся под контролем: срок не прошёл, владелец назван, секрета в реестре нет.
#
# Реестр активов — самое естественное место для утечки: рядом с адресом сервера рука
# сама дописывает ключ к нему. Правило «секреты не попадают в .claude/ и в артефакты»
# существует в security-rules.md с самого начала и до 5.2 не имело ни одной машинной
# проверки. Правило без гарда есть мнение.
#
# Замер, ради которого реестр вообще получил прибор: файл `resources.md` был заведён
# в 1 проекте из 4, содержал 27 строк и не правился 56 дней — у него не было ни одного
# читателя. Артефакт живёт ровно столько, сколько его кто-то берёт на вход.
#
# Один предмет — «актив под контролем». Три его отказа:
#   1) СЕКРЕТ В РЕЕСТРЕ — значение рядом с именем токена, ключа или пароля;
#   2) СРОК ПРОШЁЛ — оплачено до даты в прошлом: домен отключается молча;
#   3) НЕТ ВЛАДЕЛЬЦА — платить и продлевать некому.
# Плюс показ без отказа: активы, у которых срок наступает в пределах предупреждения.
#
# ЗАПУСК: bash .claude/hooks/check-assets.sh [файл-активов] [дата]
#   exit 0 — активы под контролем (или файла нет)
#   exit 1 — есть отказ, либо разобрать файл не удалось
#
# Доказательство мутацией: .claude/hooks/check-assets.test.sh

set -uo pipefail

ASSETS=${1:-${ASSETS_FILE:-project/resources.md}}
TODAY=${2:-${ASSETS_TODAY:-$(date +%F)}}
SECTION=${ASSETS_SECTION:-Активы}

[ -f "${ASSETS}" ] || { printf 'реестра активов нет (%s) — проверять нечего\n' "${ASSETS}"; exit 0; }

header() { awk 'NR==1 && $0!="---" {exit} NR==1 {next} /^---[[:space:]]*$/ {exit} {print}' "$1"; }

warn_days=$(header "${ASSETS}" | grep -m1 -E '^expiry_warning_days:' \
            | sed -E 's/^expiry_warning_days:[[:space:]]*//; s/[^0-9].*$//')
case "${warn_days}" in ''|*[!0-9]*) warn_days=30 ;; esac

# Половина «найдено не ноль» стоит на разборе: ноль активов у нового проекта законен,
# отсутствие раздела означает, что мерить нечем.
if ! grep -qE "^## ${SECTION}" "${ASSETS}"; then
  printf 'ОШИБКА: в %s нет раздела «%s» — разобрать реестр нечем.\n' "${ASSETS}" "${SECTION}" >&2
  printf 'Имя раздела — контракт с этим прибором: переименовали, и он ослеп.\n' >&2
  exit 1
fi

is_placeholder() {
  case "$1" in
    ''|'-'|'—'|'TBD'|'tbd'|'n/a') return 0 ;;
    \<*|*\>) return 0 ;;
    *) return 1 ;;
  esac
}
join_list() { printf '%s, ' "$@" | sed 's/, $//'; }
trim() { printf '%s' "$1" | sed -E 's/^[[:space:]]*//; s/[[:space:]]*$//; s/^\*+//; s/\*+$//; s/`//g'; }

# --- 1. Секрет в реестре ------------------------------------------------------
# Ищем ЗНАЧЕНИЕ рядом с именем секрета, а не само имя: строка «переменная окружения
# PROVIDER_KEY» — это адрес хранилища и она законна, а «PROVIDER_KEY=sk-abc123» —
# утечка. Различаем по наличию присваивания или длинной непробельной строки после
# двоеточия. Список имён — из knowledge/security-rules.md.
secret_hits=$(grep -nEi \
  '(token|api[_-]?key|secret|password|passwd|pwd|private[_-]?key|bearer|credential)[[:space:]]*[:=][[:space:]]*["'"'"']?[A-Za-z0-9_./+-]{12,}' \
  "${ASSETS}" 2>/dev/null || true)
# Комментарий утечку не оправдывает: файл в git, и история помнит и комментарий тоже.
# Поэтому ищем по всему файлу, а не только по строкам таблицы.

# --- 2 и 3. Срок и владелец ---------------------------------------------------
expired=()
expiring=()
no_owner=()
examined=0

while IFS= read -r row; do
  id=$(trim "$(printf '%s' "${row}" | cut -d'|' -f2)")
  owner=$(trim "$(printf '%s' "${row}" | cut -d'|' -f6)")
  paid=$(trim "$(printf '%s' "${row}" | cut -d'|' -f7)")
  examined=$((examined + 1))

  is_placeholder "${owner}" && no_owner+=("${id}")

  case "${paid}" in
    [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9])
      if [[ "${paid}" < "${TODAY}" ]]; then
        expired+=("${id} (до ${paid})")
      else
        # Граница считается от ДАТЫ ОТСЧЁТА, а не от настоящего «сегодня»: иначе
        # прибор игнорирует свой же аргумент и тест мерит календарь, а не логику.
        # Две формы date: BSD (-j -v) и GNU (-d). Обе нужны — CI идёт на Linux.
        limit=$(date -j -v"+${warn_days}d" -f '%Y-%m-%d' "${TODAY}" +%F 2>/dev/null \
                || date -d "${TODAY} +${warn_days} days" +%F 2>/dev/null \
                || printf '%s' "${TODAY}")
        [[ ! "${paid}" > "${limit}" ]] && expiring+=("${id} (до ${paid})")
      fi
      ;;
  esac
done < <(awk -v want="## ${SECTION}" '
  /<!--/ {commented=1}
  commented {if (/-->/) commented=0; next}
  $0 == want {inside=1; next}
  /^## / {inside=0}
  inside && /^\|[[:space:]]*\**[A-Z]+-[0-9]+/ {print}
' "${ASSETS}")

printf 'Активы %s: разобрано %s, предупреждение за %s дн., дата отсчёта %s.\n' \
  "${ASSETS}" "${examined}" "${warn_days}" "${TODAY}"

[ ${#expiring[@]} -eq 0 ] || printf 'Срок наступает: %s.\n' "$(join_list "${expiring[@]}")"

failed=0

if [ -n "${secret_hits}" ]; then
  printf '\nСЕКРЕТ В РЕЕСТРЕ АКТИВОВ:\n%s\n' "${secret_hits}" >&2
  printf 'В реестре хранится ТОЛЬКО адрес значения — «менеджер паролей, запись X»,\n' >&2
  printf '«переменная окружения Y», «у Founder». Значение здесь = инцидент: убери его\n' >&2
  printf 'и **ротируй** — файл уже в git, и история его помнит.\n' >&2
  failed=1
fi

if [ ${#expired[@]} -gt 0 ]; then
  printf '\nСРОК ПРОШЁЛ (%s): %s.\n' "${#expired[@]}" "$(join_list "${expired[@]}")" >&2
  printf 'Домен, сервер или услуга с истёкшим сроком отключается молча — и узнают об этом\n' >&2
  printf 'по упавшему проду. Продли и обнови дату, либо перенеси актив в «Снятые».\n' >&2
  failed=1
fi

if [ ${#no_owner[@]} -gt 0 ]; then
  printf '\nНЕТ ВЛАДЕЛЬЦА (%s): %s.\n' "${#no_owner[@]}" "$(join_list "${no_owner[@]}")" >&2
  printf 'Владелец — тот, кто платит и продлевает, а не тот, кто пользуется. Без него\n' >&2
  printf 'актив продлевать некому: каждый считает, что это чужая забота.\n' >&2
  failed=1
fi

if [ "${examined}" -eq 0 ] && [ "${failed}" -eq 0 ]; then
  printf 'Записей ноль — либо активы не записывали, либо их нет. Домен, сервер и оплаченная\n'
  printf 'услуга появляются раньше, чем про них вспоминают: проверь, что нечего записать.\n'
fi

[ "${failed}" -eq 0 ] || exit 1
exit 0
