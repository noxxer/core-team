#!/bin/bash
# Приёмка дорожек: доехала ли работа субагентов до файлов, названных в брифе.
#
# ТИР: волна — вызывается после волны субагентов, не в конце сессии
#
# Замер, из которого вырос гард: в боевой сессии ТРИ ДОРОЖКИ ИЗ ШЕСТИ потеряли
# работу целиком — писали результат последним действием, и падение агента
# уносило её всю. Отчёты при этом были бодрыми. Во втором проекте из шести
# запросов ревью большинство субагентов завершилось без отчёта.
# Поэтому проверка идёт ПО ФАЙЛУ, а не по отчёту агента.
#
# Вызов: check-lane-acceptance.sh [--since <unix-время>] <путь> [<путь>...]
#   --since  отсекает наследие прошлого прогона: файл, не менявшийся с начала
#            волны, приёмкой не является, хотя лежит на месте и не пуст.
#
# Exit 0 — все дорожки приняты
# Exit 1 — хотя бы одна не доехала, либо принимать было нечего

set -uo pipefail

SINCE=""
PATHS=()

while [ $# -gt 0 ]; do
  case "$1" in
    --since)
      shift
      [ $# -gt 0 ] || { echo "приёмка: ключ --since без значения." >&2; exit 1; }
      SINCE="$1"
      ;;
    --since=*) SINCE="${1#--since=}" ;;
    --help|-h) sed -n '2,15p' "$0"; exit 0 ;;
    -*) echo "приёмка: неизвестный ключ ${1}." >&2; exit 1 ;;
    *) PATHS+=("$1") ;;
  esac
  shift
done

# --- Половина «найдено не ноль» ---------------------------------------------
# Гард, которому не дали предмет, не имеет права сказать «всё доехало».
if [ "${#PATHS[@]}" -eq 0 ]; then
  echo "приёмка: не передано ни одного пути — принимать нечего." >&2
  echo "Если волна была, приёмка каждой дорожки называется в брифе ДО запуска." >&2
  exit 1
fi

if [ -n "${SINCE}" ]; then
  case "${SINCE}" in
    ''|*[!0-9]*)
      echo "приёмка: --since ожидает unix-время в секундах, получено «${SINCE}»." >&2
      exit 1
      ;;
  esac
fi

mtime_of() {
  if [ "$(uname)" = "Darwin" ]; then stat -f %m "$1" 2>/dev/null
  else stat -c %Y "$1" 2>/dev/null; fi
}

accepted=0
lost=0

for lane in "${PATHS[@]}"; do
  if [ -d "${lane}" ]; then
    printf '🔴 %s — это каталог, а не файл приёмки.\n' "${lane}"
    lost=$((lost + 1)); continue
  fi
  if [ ! -e "${lane}" ]; then
    printf '🔴 %s — файла нет. Работа дорожки не доехала.\n' "${lane}"
    lost=$((lost + 1)); continue
  fi
  if [ ! -s "${lane}" ] || ! grep -q '[^[:space:]]' "${lane}" 2>/dev/null; then
    printf '🔴 %s — файл заведён, содержимого нет.\n' "${lane}"
    lost=$((lost + 1)); continue
  fi
  if [ -n "${SINCE}" ]; then
    modified=$(mtime_of "${lane}")
    if ! [ "${modified:-}" -eq "${modified:-}" ] 2>/dev/null; then
      printf '🔴 %s — не удалось прочитать время изменения; приёмка не подтверждается.\n' "${lane}"
      lost=$((lost + 1)); continue
    fi
    if [ "${modified}" -lt "${SINCE}" ]; then
      printf '🔴 %s — не менялся с начала волны: это наследие прошлого прогона.\n' "${lane}"
      lost=$((lost + 1)); continue
    fi
  fi
  printf '🟢 %s — принято (%s байт).\n' "${lane}" "$(wc -c < "${lane}" | tr -d ' ')"
  accepted=$((accepted + 1))
done

printf '\nДорожек: %s. Принято: %s. Не доехало: %s.\n' "${#PATHS[@]}" "${accepted}" "${lost}"

# Граница собственной силы названа в выводе, а не только в документации:
# без --since приёмка, дописываемая в УЖЕ существующий файл, пройдёт даже
# если дорожка не сделала ничего.
if [ -z "${SINCE}" ]; then
  printf 'Оговорка: --since не задан — приёмка не отличает свежую работу от лежавшей до волны.\n'
fi

if [ "${lost}" -gt 0 ]; then
  printf 'Прежде чем респаунить упавшую дорожку — прочитай уцелевшие файлы: агент мог оставить готовую работу.\n'
  exit 1
fi
exit 0
