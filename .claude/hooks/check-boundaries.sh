#!/bin/bash
# Граница между контурами либо сверяется машинно, либо это долг с датой и владельцем.
#
# ТИР: стоп — граница без сверки пропускает расхождение формы в прод молча
#
# Замер, ради которого прибор написан. В боевом проекте (Django + React) расхождение
# формы на границе фронт↔бек рецидивировало ДЕСЯТЬ раз на протяжении двадцати двух
# фич. Против него стояли пять слоёв: именованный чеклист ревью, запись в реестре
# рисков с наивысшим весом (P×I=16), FMEA, решение о генерации типов из схемы и
# CI-гейт `codegen → git diff --exit-code`.
#
# Аудит шестью независимыми аудиторами назвал причину: гейт СУЩЕСТВОВАЛ И НЕ
# ВЫЗЫВАЛСЯ в CI, оба тест-гейта стояли с `allow_failure: true`, а проверка
# соответствия засчитывала 404 на маршруте как успех. Дословно: «риски не в коде,
# а в отключённых предохранителях».
#
# ЕДИНИЦА — ПАРА СТОРОН, А НЕ ВЫЗОВ. Замер: 181 уникальный путь `/api/…` в одних
# только артефактах того же проекта. Реестр по ручке на строку стал бы лентой без
# дна за месяц — ровно судьба реестра рисков на 1290 строк. Границ при этом пять-шесть.
#
# ТРЕТЬЕГО СОСТОЯНИЯ НЕТ. Граница сверяется адресуемым гардом либо объявлена долгом
# с датой и владельцем. «Сверяем глазами при правке» — не сверка, а её отсутствие:
# принятое без даты, оно горит красным вечно, а на вечное красное перестают смотреть.
# Долг даёт третий вид красного: пока дата не прошла — зелено и перечислено явно.
#
# Один предмет — «граница под контролем». Пять его отказов:
#   1) СТОРОНЫ НЕ НАЗВАНЫ — в имени границы нет двух сторон; «API» границей не является;
#   2) ИСТОЧНИК ФОРМЫ НЕ НАЗВАН — сверять не с чем;
#   3) ГРАНИЦА БЕЗ СВЕРКИ — ячейка пуста либо содержит прозу вместо адреса и долга;
#   4) АДРЕС ВЕДЁТ В НИКУДА — путь назван, файла нет;
#   5) ДОЛГ ПРОСРОЧЕН — дата, до которой приняли, прошла.
# Плюс показ без отказа: живые долги, отставшая сверка, объявленные обходы.
#
# ЧЕГО ЭТОТ ПРИБОР НЕ ДЕЛАЕТ. Он не сверяет форму — это работа гарда проекта, и она
# зависит от языка. И он слеп к расхождению СМЫСЛА при совпавшей форме (боевой случай:
# поле `p50` содержит суммарное время, фронт подписывает «активное», типы совпадают).
# Смысл ловится предъявлением — точка `scenario-verification`, не эта.
#
# ЗАПУСК: bash .claude/hooks/check-boundaries.sh [файл-границ] [дата]
#   exit 0 — границы под контролем (или файла нет)
#   exit 1 — есть отказ, либо разобрать файл не удалось
#
# Доказательство мутацией: .claude/hooks/check-boundaries.test.sh

set -uo pipefail

BOUNDARIES=${1:-${BOUNDARIES_FILE:-project/boundaries.md}}
# Корень, от которого разрешаются пути в колонках «источник» и «чем сверяется».
ROOT_DIR=${BOUNDARIES_ROOT:-.}
TODAY=${2:-${BOUNDARIES_TODAY:-$(date +%F)}}
SECTION=${BOUNDARIES_SECTION:-Границы}

[ -f "${BOUNDARIES}" ] || { printf 'реестра границ нет (%s) — проверять нечего\n' "${BOUNDARIES}"; exit 0; }

# Шапку читаем общей библиотекой: комментарий после значения — не значение.
# Сломанная библиотека прибор не роняет, разбор идёт прежним путём.
LIB=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib-frontmatter.sh
# shellcheck source=/dev/null
[ -f "${LIB}" ] && . "${LIB}" 2>/dev/null
if ! command -v fm_field >/dev/null 2>&1; then
  fm_field() {
    awk 'NR==1 && $0!="---" {exit} NR==1 {next} /^---[[:space:]]*$/ {exit} {print}' "$1" 2>/dev/null \
      | grep -m1 -E "^$2:" | sed -E "s/^$2:[[:space:]]*//; s/[[:space:]]*#.*$//; s/\"//g"
  }
fi

stale_days=$(fm_field "${BOUNDARIES}" 'stale_days' | tr -cd '0-9')
case "${stale_days}" in ''|*[!0-9]*) stale_days=90 ;; esac

# Половина «найдено не ноль» стоит на разборе: ноль границ у нового проекта законен,
# отсутствие раздела означает, что мерить нечем.
if ! grep -qE "^## ${SECTION}" "${BOUNDARIES}"; then
  printf 'ОШИБКА: в %s нет раздела «%s» — разобрать реестр нечем.\n' "${BOUNDARIES}" "${SECTION}" >&2
  printf 'Имя раздела — контракт с этим прибором: переименовали, и он ослеп.\n' >&2
  exit 1
fi

is_placeholder() {
  case "$1" in
    ''|'-'|'—'|'?'|'TBD'|'tbd'|'n/a') return 0 ;;
    \<*|*\>) return 0 ;;
    *) return 1 ;;
  esac
}
join_list() { printf '%s, ' "$@" | sed 's/, $//'; }
trim() { printf '%s' "$1" | sed -E 's/^[[:space:]]*//; s/[[:space:]]*$//; s/^\*+//; s/\*+$//; s/`//g'; }

# Похоже ли значение на путь внутри проекта. Проверяется ПОСЛЕ проверки существования:
# `Makefile` существует и без косой черты, а `codegen:check` не существует и путём
# не является — порядок решает, какое из двух сообщений получит человек.
looks_like_path() {
  # Запись с пробелом путём не является. Без этого условия проза с точкой или
  # косой чертой объявлялась битым адресом: «внешний: Jira REST v3.0», «схема в
  # app.config.ts», «смотрим на ревью п.3» — три ложных находки на прогоне аудита,
  # и все три на записях, которые человек имел полное право написать.
  case "$1" in
    *[[:space:]]*) return 1 ;;
    */*) return 0 ;;
    *.*) return 0 ;;
    *) return 1 ;;
  esac
}

# Часть значения до указания места внутри файла: `.gitlab-ci.yml::codegen:check`
# и `docs/contract.md#раздел` — адреса одного файла с уточнением.
path_head() { printf '%s' "${1%%::*}" | sed -E 's/#.*$//'; }

# Битые пути источника собираются в файл: внутренний разбор цепочки идёт конвейером,
# то есть в подоболочке, и массив оттуда наружу не вернётся.
DEAD_TMP=$(mktemp)
trap 'rm -f "${DEAD_TMP}"' EXIT

no_sides=()
no_source=()
no_check=()
dead_path=()
expired_debt=()
live_debt=()
stale=()
bypass=0
examined=0
unmeasured=0

# Граница отставания сверки. Две формы `date`: BSD (-j -v) и GNU (-d). CI идёт на Linux,
# рабочая машина на macOS — нужны обе. Не сработала ни одна: это не «сверки свежие»,
# а несостоявшееся измерение, и оно называется вслух.
stale_before=$(date -j -v"-${stale_days}d" -f '%Y-%m-%d' "${TODAY}" +%F 2>/dev/null \
               || date -d "${TODAY} -${stale_days} days" +%F 2>/dev/null \
               || printf 'НЕИЗМЕРИМО')
[ "${stale_before}" = "НЕИЗМЕРИМО" ] && unmeasured=1

while IFS= read -r row; do
  id=$(trim "$(printf '%s' "${row}" | cut -d'|' -f2)")
  sides=$(trim "$(printf '%s' "${row}" | cut -d'|' -f3)")
  source_of=$(trim "$(printf '%s' "${row}" | cut -d'|' -f4)")
  verified_by=$(trim "$(printf '%s' "${row}" | cut -d'|' -f5)")
  bypasses=$(trim "$(printf '%s' "${row}" | cut -d'|' -f6)")
  last_seen=$(trim "$(printf '%s' "${row}" | cut -d'|' -f7)")
  examined=$((examined + 1))

  # --- 1. Стороны -------------------------------------------------------------
  # У границы всегда двое. Одно слово («API», «контракты») сторон не называет:
  # непонятно, кто с кем договаривается, и некому разойтись.
  case "${sides}" in
    *"↔"*|*"<->"*) ;;
    *) no_sides+=("${id}") ;;
  esac

  # --- 2. Источник правды о форме ---------------------------------------------
  if is_placeholder "${source_of}"; then
    no_source+=("${id}")
  else
    # Источник бывает цепочкой: «schemas.py → openapi.json». Проверяем каждое звено,
    # похожее на путь; «внешний, не наш» путём не является и проверке не подлежит.
    printf '%s' "${source_of}" | tr ',' '\n' | awk '{gsub(/→/, "\n"); print}' | while IFS= read -r part; do
      part=$(trim "${part}")
      [ -n "${part}" ] || continue
      head=$(path_head "${part}")
      [ -e "${ROOT_DIR}/${head}" ] && continue
      looks_like_path "${head}" || continue
      printf '%s → %s\n' "${id}" "${head}"
    done >> "${DEAD_TMP}"
  fi

  # --- 3, 4, 5. Сверка: адрес, долг или ничего --------------------------------
  debt_until=$(printf '%s' "${verified_by}" \
               | grep -oE 'долг[^0-9]{0,20}[0-9]{4}-[0-9]{2}-[0-9]{2}' \
               | grep -oE '[0-9]{4}-[0-9]{2}-[0-9]{2}' | head -1)
  if [ -n "${debt_until}" ]; then
    if [[ "${debt_until}" < "${TODAY}" ]]; then
      expired_debt+=("${id} (долг до ${debt_until})")
    else
      live_debt+=("${id} (до ${debt_until})")
    fi
  elif is_placeholder "${verified_by}"; then
    no_check+=("${id}")
  else
    head=$(path_head "${verified_by}")
    if [ -e "${ROOT_DIR}/${head}" ]; then
      :
    elif looks_like_path "${head}"; then
      dead_path+=("${id} → ${head}")
    else
      # Проза вместо адреса: «сверяем глазами», «на ревью», «codegen». Это не гард —
      # ни один из них нельзя запустить и увидеть красным.
      no_check+=("${id}")
    fi
  fi

  # --- Показ ------------------------------------------------------------------
  is_placeholder "${bypasses}" || bypass=$((bypass + 1))

  case "${last_seen}" in
    [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9])
      [ "${unmeasured}" -eq 1 ] && continue
      [[ "${last_seen}" < "${stale_before}" ]] && stale+=("${id} (${last_seen})")
      ;;
  esac
done < <(awk -v want="## ${SECTION}" '
  /<!--/ {commented=1}
  commented {if (/-->/) commented=0; next}
  $0 == want {inside=1; next}
  /^## / {inside=0}
  inside && /^\|[[:space:]]*\**[A-Z]+-[0-9]+/ {print}
' "${BOUNDARIES}")

# Забираем то, что собрала подоболочка.
if [ -s "${DEAD_TMP}" ]; then
  while IFS= read -r line; do dead_path+=("${line}"); done < "${DEAD_TMP}"
fi

printf 'Границы %s: разобрано %s, отставание сверки от %s дн., дата отсчёта %s.\n' \
  "${BOUNDARIES}" "${examined}" "${stale_days}" "${TODAY}"

[ ${#live_debt[@]} -eq 0 ] || printf 'Принято как долг (%s): %s.\n' "${#live_debt[@]}" "$(join_list "${live_debt[@]}")"
[ ${#stale[@]} -eq 0 ] || printf 'Сверка отстала (%s): %s.\n' "${#stale[@]}" "$(join_list "${stale[@]}")"
[ "${examined}" -eq 0 ] || printf 'Обходы объявлены у %s границ из %s.\n' "${bypass}" "${examined}"
[ "${unmeasured}" -eq 0 ] || printf 'Отставание сверки не проверено: ни BSD-, ни GNU-форма `date` не сработала.\n'

failed=0

if [ ${#no_check[@]} -gt 0 ]; then
  printf '\nГРАНИЦА БЕЗ СВЕРКИ (%s): %s.\n' "${#no_check[@]}" "$(join_list "${no_check[@]}")" >&2
  printf 'Расхождение формы на такой границе уезжает в прод молча: зелёные тесты его\n' >&2
  printf 'не видят, потому что обе стороны согласны сами с собой. Одно из двух: назови\n' >&2
  printf 'адрес гарда (`ci/check-api.sh`, `.gitlab-ci.yml::codegen:check`) либо объяви\n' >&2
  printf 'долг — «принято как долг до 2026-10-31, владелец dev». Проза сверкой не является.\n' >&2
  failed=1
fi

if [ ${#expired_debt[@]} -gt 0 ]; then
  printf '\nДОЛГ ПРОСРОЧЕН (%s): %s.\n' "${#expired_debt[@]}" "$(join_list "${expired_debt[@]}")" >&2
  printf 'Дата, до которой границу приняли без сверки, прошла — красное вернулось.\n' >&2
  printf 'Либо строй гард и называй его адрес, либо продлевай долг новой датой и причиной.\n' >&2
  failed=1
fi

if [ ${#dead_path[@]} -gt 0 ]; then
  printf '\nАДРЕС ВЕДЁТ В НИКУДА (%s): %s.\n' "${#dead_path[@]}" "$(join_list "${dead_path[@]}")" >&2
  printf 'Названного файла нет. Указатель в никуда дороже пустой ячейки: он выглядит\n' >&2
  printf 'ответом, и граница считается сверяемой, пока кто-нибудь не пойдёт по адресу.\n' >&2
  failed=1
fi

if [ ${#no_sides[@]} -gt 0 ]; then
  printf '\nСТОРОНЫ НЕ НАЗВАНЫ (%s): %s.\n' "${#no_sides[@]}" "$(join_list "${no_sides[@]}")" >&2
  printf 'У границы всегда двое: «фронт ↔ бек», «бек ↔ Jira REST», «код ↔ алерты».\n' >&2
  printf 'Одно слово вроде «API» не называет, кто с кем договаривается, — и разойтись\n' >&2
  printf 'в такой записи некому.\n' >&2
  failed=1
fi

if [ ${#no_source[@]} -gt 0 ]; then
  printf '\nИСТОЧНИК ФОРМЫ НЕ НАЗВАН (%s): %s.\n' "${#no_source[@]}" "$(join_list "${no_source[@]}")" >&2
  printf 'Сверять не с чем: у формы должен быть один источник — файл схемы, модель\n' >&2
  printf 'или внешний контракт (так и пиши: «внешний, не наш»). Два источника правды\n' >&2
  printf 'о форме — это уже расхождение, просто ещё не замеченное.\n' >&2
  failed=1
fi

if [ "${examined}" -eq 0 ] && [ "${failed}" -eq 0 ]; then
  printf 'Записей ноль — либо границы не описывали, либо контур один. Фронт и бек, внешний\n'
  printf 'сервис, очередь, алерты: граница появляется раньше, чем про неё вспоминают.\n'
fi

[ "${failed}" -eq 0 ] || exit 1
exit 0
