#!/bin/bash
# Библиотека, а не проверка: помогает проверкам спросить у таблицы подключений,
# чем закрыт слой работы и где лежит его результат.
#
# Зачем она есть. Таблица подключений отвечает на вопрос «чем закрыт каждый слой
# и где искать результат». До появления этой библиотеки её читала ровно одна
# проверка — та, которая саму таблицу и проверяет. Остальные ходили по адресам,
# записанным внутри них самих, и на проекте, где слой ведёт сторонний инструмент,
# сообщали «записей ноль» при восьми записях.
#
# Подключается строкой `source "$(dirname "${BASH_SOURCE[0]}")/lib-points.sh"`.
# Файла нет — вызывающая проверка обязана продолжить работу по своему адресу
# и сказать об этом: сломанная библиотека не должна ронять проверку.

# Кто закрывает слой: имя инструмента, слово «ядро» или пусто.
point_closed_by() {  # $1 = имя точки, $2 = файл таблицы
  local name=$1 file=${2:-project/connection-points.md}
  [ -f "${file}" ] || return 0
  grep -E "^\|[[:space:]]*\`${name}\`[[:space:]]*\|" "${file}" 2>/dev/null \
    | head -1 \
    | awk -F'|' '{gsub(/^[[:space:]]+|[[:space:]]+$/, "", $4); gsub(/[`*]/, "", $4); print $4}' \
    | sed 's/@.*$//'
}

# Где лежит результат слоя: путь от корня проекта или пусто.
point_location() {  # $1 = имя точки, $2 = файл таблицы
  local name=$1 file=${2:-project/connection-points.md} value
  [ -f "${file}" ] || return 0
  value=$(grep -E "^\|[[:space:]]*\`${name}\`[[:space:]]*\|" "${file}" 2>/dev/null \
          | head -1 \
          | awk -F'|' '{gsub(/^[[:space:]]+|[[:space:]]+$/, "", $6); gsub(/[`*]/, "", $6); print $6}')
  case "$(printf '%s' "${value}" | tr -d '[:space:]')" in
    ''|'—'|'-'|'–') return 0 ;;
    *) printf '%s' "${value}" ;;
  esac
}

# Слой ведёт сторонний инструмент? Тогда содержание проверяет он, а не ядро.
point_is_external() {  # $1 = имя точки, $2 = файл таблицы
  local who
  who=$(point_closed_by "$1" "${2:-}")
  case "$(printf '%s' "${who}" | tr -d '[:space:]')" in
    ''|'—'|'-'|'–'|ядро|ядра|core) return 1 ;;
    *) return 0 ;;
  esac
}
