#!/bin/bash
#
# ТИР: копия — про переносимость инструмента, а не про проект
#
# Инструмент работает и на macOS, и на Linux. Проверяется это не shellcheck.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИБОР. shellcheck разбирает **синтаксис оболочки** и ничего не
# знает об аргументах чужих программ. Проба: файл с четырьмя платформенными
# несовместимостями подряд (`date -j`, `stat -f`, `grep -P`, `readlink -f`) даёт
# **ноль** замечаний shellcheck на любом уровне строгости. Значит кросс-платформенность
# он не покрывает, и её надо мерить самим.
#
# Три класса, каждый пойман на этом проекте:
#   1) ПАРА РАЗОШЛАСЬ — использована форма одной платформы без формы другой:
#      `date -j`/`date -v` (BSD) требуют `date -d` (GNU) рядом; `stat -f` требует
#      `stat -c`. Замер: ветви GNU-`date` не исполнялись НИ РАЗУ до первого прогона
#      в CI, и при отказе обеих форм приборы молча зеленели;
#   2) ТОЛЬКО GNU — утилита или флаг, которых на macOS нет вовсе;
#   3) BSD-СПЕЦИФИЧНАЯ ФОРМА — `sed -i ''`: на GNU пустая строка становится скриптом,
#      правка молча не происходит, и тест проходит по неверной причине;
#      `match(str, re, arr)` — третий аргумент есть только в GNU awk, на BSD молча
#      игнорируется, ветка не берётся, прибор считает неверно и остаётся зелёным.
#
# Все три класса объединены здесь, потому что предмет один — «инструмент переносим».
# Раньше они жили тремя отдельными шагами CI: три копии одного предмета в одном файле.
#
# ЗАПУСК: bash .claude/hooks/check-portability.sh [каталог]
#   exit 0 — переносимо
#   exit 1 — есть непереносимое место, либо проверять оказалось нечего
#
# Доказательство мутацией: .claude/hooks/check-portability.test.sh

set -uo pipefail

SCAN=${1:-${PORTABILITY_SCAN:-.claude/hooks}}

[ -d "${SCAN}" ] || { printf 'ОШИБКА: нет каталога %s — проверять нечего.\n' "${SCAN}" >&2; exit 1; }

join_list() { printf '%s, ' "$@" | sed 's/, $//'; }

# Строки-комментарии из разбора убираем: прибор не должен краснеть на объяснении
# самого себя. Обратные кавычки — тоже упоминание, а не вызов.
code_lines() { grep -nE "$1" "$2" 2>/dev/null | grep -v ':[[:space:]]*#' | grep -v '`' || true; }

# Литерал, который нельзя писать литералом: см. ниже, где он применяется.
quote=$(printf "'")
bad_sed="sed -i ${quote}${quote}"

files=0
broken_pairs=()
gnu_only=()
bsd_forms=()
nonascii=()

for f in "${SCAN}"/*.sh; do
  [ -f "${f}" ] || continue
  files=$((files + 1))
  name=$(basename "${f}")

  # --- 1. Пары платформенных форм ---
  for rule in 'date[[:space:]]+-j|date[[:space:]]+-d|date -j без date -d' \
              'date[[:space:]]+-v|date[[:space:]]+-d|date -v без date -d' \
              'stat[[:space:]]+-f|stat[[:space:]]+-c|stat -f без stat -c'; do
    bsd=${rule%%|*}; rest=${rule#*|}; gnu=${rest%%|*}; label=${rest#*|}
    if [ -n "$(code_lines "${bsd}" "${f}")" ] && [ -z "$(code_lines "${gnu}" "${f}")" ]; then
      broken_pairs+=("${name}: ${label}")
    fi
  done

  # --- 2. Только GNU: на macOS нет вовсе, запасной формы не существует ---
  for pat in 'grep[[:space:]]+-P' 'sort[[:space:]]+-V' 'readlink[[:space:]]+-f' \
             'xargs[[:space:]]+-r' 'base64[[:space:]]+-w' '\-printf[[:space:]]'; do
    [ -n "$(code_lines "${pat}" "${f}")" ] && gnu_only+=("${name}: ${pat}")
  done

  # --- 3. BSD-специфичные формы, молчащие на GNU ---
  # Образец собирается на лету: написанный литералом, он нашёл бы сам себя, и
  # прибор краснел бы на собственном определении. Класс пойман первым же прогоном.
  [ -n "$(grep -nF "${bad_sed}" "${f}" 2>/dev/null | grep -v ':[[:space:]]*#' | grep -v '`' || true)" ] \
    && bsd_forms+=("${name}: sed -i с пустым аргументом (на GNU правка молча не происходит)")
  [ -n "$(code_lines 'match\([^)]+,[^)]+,[^)]+\)' "${f}")" ] \
    && bsd_forms+=("${name}: match() с тремя аргументами (только GNU awk)")

  # --- 4. Имя переменной упирается в не-ASCII: bash забирает первый байт символа ---
  [ -n "$(grep -nP '\$[A-Za-z_][A-Za-z0-9_]*[^\x00-\x7F]' "${f}" 2>/dev/null | head -1 || true)" ] \
    && nonascii+=("${name}")
done

# Половина «найдено не ноль»: каталог есть, а файлов ноль — перечисляющая проверка
# на пустом множестве проходит по построению и успехом не является.
if [ "${files}" -eq 0 ]; then
  printf 'ОШИБКА: в %s нет ни одного файла .sh — проверять нечего.\n' "${SCAN}" >&2
  exit 1
fi

printf 'Переносимость %s: осмотрено файлов %s.\n' "${SCAN}" "${files}"

failed=0

if [ ${#broken_pairs[@]} -gt 0 ]; then
  printf '\nПАРА ПЛАТФОРМЕННЫХ ФОРМ РАЗОШЛАСЬ (%s): %s.\n' "${#broken_pairs[@]}" "$(join_list "${broken_pairs[@]}")" >&2
  printf 'Форма одной платформы без формы другой: на второй прибор молча деградирует.\n' >&2
  printf 'Пиши обе через `||` и делай отказ ОБЕИХ видимым — «не измерено» ≠ «чисто».\n' >&2
  failed=1
fi

if [ ${#gnu_only[@]} -gt 0 ]; then
  printf '\nТОЛЬКО GNU (%s): %s.\n' "${#gnu_only[@]}" "$(join_list "${gnu_only[@]}")" >&2
  printf 'На macOS этого нет вовсе, и запасной формы не существует — нужен другой приём.\n' >&2
  failed=1
fi

if [ ${#bsd_forms[@]} -gt 0 ]; then
  printf '\nФОРМА, МОЛЧАЩАЯ НА ЧУЖОЙ ПЛАТФОРМЕ (%s): %s.\n' "${#bsd_forms[@]}" "$(join_list "${bsd_forms[@]}")" >&2
  printf 'Самый дорогой класс: ошибки нет, поведение другое, прогон остаётся зелёным.\n' >&2
  failed=1
fi

if [ ${#nonascii[@]} -gt 0 ]; then
  printf '\nИМЯ ПЕРЕМЕННОЙ УПИРАЕТСЯ В НЕ-ASCII (%s): %s.\n' "${#nonascii[@]}" "$(join_list "${nonascii[@]}")" >&2
  printf 'bash заберёт первый байт многобайтового символа в имя переменной, и `set -u`\n' >&2
  printf 'уронит скрипт. Подставь фигурные скобки: ${var}.\n' >&2
  failed=1
fi

[ "${failed}" -eq 0 ] || exit 1
printf 'Непереносимых мест нет.\n'
exit 0
