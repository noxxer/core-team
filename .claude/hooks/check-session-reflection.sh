#!/bin/bash
# Проверщик рефлексии: последняя записанная сессия должна содержать непустые
#
# ТИР: стоп — сессия не записана — восстановить нечем
# слоты Navigator-разбора.
#
# Замер, из которого выросла проверка: Navigator-анализ есть в 68-75% недавних
# сессий, а в итоговый отчёт Founder-у попадает в 27% (6 из 22). Плюс измеренная
# связь «слот в шаблоне → результат»: Iceberg (слот есть) — 36 и 26 сессий,
# Three Why (слота не было) — 4 и 7.
#
# УНАСЛЕДОВАННАЯ СЕССИЯ ПЕРЕЧИСЛЯЕТСЯ, НО НЕ РОНЯЕТ. Слоты смыслов и условие
# выхода приехали в 5.1.0 (2026-08-26); сессия, записанная раньше, не могла их
# содержать. Прибор это знал и печатал «для унаследованных это норма» — и всё
# равно возвращал отказ. Замер восьми боевых проектов: во ВСЕХ восьми находка
# одна и та же — четыре отсутствующих слота высшего тира, — то есть гейт
# `/end-session` не проходил нигде и требовал разобрать то, чего не вернуть:
# рефлексия по давно записанной сессии уже потеряна, и красное её не воскресит.
# Ставка была назначена неверно: находка не ломает следующую сессию.
#
# Дата берётся из имени каталога сессии и сравнивается с REFLECTION_ENFORCED_SINCE —
# тем же ходом, что у `check-decisions.sh` и `check-decision-decay.sh`. Свежая
# сессия без слотов роняет по-прежнему: это не наследие, а запись своими словами
# мимо шаблона (замер боевого прогона — так случилось дважды).
#
# ЗАПУСК: bash .claude/hooks/check-session-reflection.sh [каталог сессий]
#   exit 0 — слоты заполнены, сессий ещё нет, либо сессия унаследованная
#   exit 1 — в сессии новее правила слот пуст или отсутствует
#
# Доказательство мутацией: check-session-reflection.test.sh

set -uo pipefail

SESSIONS_DIR=${1:-${SESSIONS_DIR:-project/sessions}}

# Дата, с которой слоты смыслов и условие выхода появились в шаблоне сессии (5.1.0).
ENFORCED_SINCE=${REFLECTION_ENFORCED_SINCE:-2026-08-26}
SLOTS=('Структура (Iceberg)' 'Три «Почему»' 'Слепые зоны (System Operator)' 'Ловушки сессии')

# Содержимое раздела: строки до следующего заголовка того же или высшего уровня.
section_body() {  # $1 = файл, $2 = заголовок
  awk -v want="$2" '
    /^#{2,4}[[:space:]]/ { inside = (index($0, want) > 0); next }
    inside { print }
  ' "$1" 2>/dev/null
}

# Слот считается заполненным, если в нём есть хоть одна содержательная строка:
# не пустая, не подсказка шаблона в квадратных скобках, не цитата-пояснение.
slot_is_filled() {
  local body=$1 line in_hint=0
  while IFS= read -r line; do
    # Подсказка шаблона занимает СКОЛЬКО УГОДНО строк: `[` открывает, `]` закрывает.
    # Продолжение подсказки со скобки не начинается — и раньше считалось содержимым.
    # Замер: сессия, скопированная из шаблона один в один, показывала «Заполнено: 1»
    # из четырёх, потому что у слота «Ловушки сессии» подсказка в две строки.
    if [ "$in_hint" -eq 1 ]; then
      case "$line" in *']'*) in_hint=0 ;; esac
      continue
    fi
    case "$line" in
      ''|'>'*) continue ;;
      \[*\]) continue ;;
      \[*) in_hint=1; continue ;;
    esac
    [ -n "$(printf '%s' "$line" | tr -d '[:space:]')" ] && return 0
  done <<< "$body"
  return 1
}

[ -d "$SESSIONS_DIR" ] || { printf 'сессий ещё нет (%s отсутствует) — проверять нечего\n' "$SESSIONS_DIR"; exit 0; }

shopt -s nullglob
files=("$SESSIONS_DIR"/*/session.md)
if [ ${#files[@]} -eq 0 ]; then
  printf 'записанных сессий пока нет — проверять нечего\n'
  exit 0
fi

# Последняя сессия. Имя каталога — `ГГГГ-ММ-ДД_тема`, и внутри одного дня оно
# упорядочивает по теме, а не по времени: замер боевого прогона — три сессии за
# день, проверенной оказалась вторая по времени. Поэтому среди файлов последней
# даты берём самый свежий по времени изменения.
latest=""
latest_date=""
for file in "${files[@]}"; do
  day=$(basename "$(dirname "$file")" | cut -c1-10)
  if [ -z "$latest" ] || [[ "$day" > "$latest_date" ]]; then
    latest=$file; latest_date=$day; continue
  fi
  if [ "$day" = "$latest_date" ] && [ "$file" -nt "$latest" ]; then
    latest=$file
  fi
done

missing=()
empty=()
for slot in "${SLOTS[@]}"; do
  if ! grep -qF -- "$slot" "$latest"; then
    missing+=("$slot")
    continue
  fi
  slot_is_filled "$(section_body "$latest" "$slot")" || empty+=("$slot")
done

# --- Вторая работа: контракт сессии ------------------------------------------
# Замер: сессия без объявленного условия выхода заканчивается там, где кончилось
# внимание, а не там, где готов результат. Проверяем не формулировку, а факт:
# условие заявлено и по нему вынесен вердикт. Подсказка шаблона в квадратных
# скобках заполнением не считается — как и у слотов смыслов.
exit_problems=()
if grep -qF -- 'Условие выхода' "$latest"; then
  for field in 'Заявлено' 'Достигнуто'; do
    value=$(grep -m1 -E "^[[:space:]]*[-*][[:space:]]*\*\*${field}:\*\*" "$latest" \
            | sed -E "s/^[[:space:]]*[-*][[:space:]]*\*\*${field}:\*\*[[:space:]]*//")
    case "${value}" in
      ''|\[*) exit_problems+=("${field}") ;;
    esac
  done
else
  exit_problems+=('раздела нет')
fi

printf 'Проверена сессия: %s. Слотов: %s. Заполнено: %s.\n' \
  "$(basename "$(dirname "$latest")")" "${#SLOTS[@]}" "$(( ${#SLOTS[@]} - ${#missing[@]} - ${#empty[@]} ))"

# Сессия, записанная до введения правила, содержать слотов не могла. Её находки
# перечисляются в обычном выводе и прогон не роняют — тем же ходом, каким
# `check-decisions.sh` перечисляет унаследованные решения. Поток здесь не
# оформление, а адрес: сводка находок читает stderr, и находка, напечатанная
# туда, попадёт в список «разбирается сейчас» независимо от кода возврата.
# Двух признаков мало по отдельности, нужны оба. Дата говорит, что шаблона тогда
# ещё не было; отсутствие ВСЕХ слотов говорит, что сессия и правда писалась по
# старому. Старая сессия, где слоты есть, писалась по новому шаблону — её автор
# правило знал, и наследие тут ни при чём. Случай пойман набором: без второго
# признака наследие прощало небрежность, а не отсутствие возможности.
legacy=no
if [ -n "${latest_date}" ] && [[ "${latest_date}" < "${ENFORCED_SINCE}" ]] \
   && [ ${#missing[@]} -eq ${#SLOTS[@]} ]; then
  legacy=yes
fi

say() { if [ "${legacy}" = yes ]; then printf '%s' "$1"; else printf '%s' "$1" >&2; fi; }

status=0
if [ ${#missing[@]} -gt 0 ]; then
  say "$(printf '\nСЛОТА НЕТ (%s): %s\n' "${#missing[@]}" "$(printf '«%s» ' "${missing[@]}")")"
  say "$(printf 'Шаблон: .claude/templates/project/session-template.md, раздел «Смыслы (Navigator)».\n')"
  [ "${legacy}" = yes ] || status=1
fi
if [ ${#empty[@]} -gt 0 ]; then
  say "$(printf '\nСЛОТ ПУСТ (%s): %s\n' "${#empty[@]}" "$(printf '«%s» ' "${empty[@]}")")"
  say "$(printf 'Нечего сказать — так и напиши («не обнаружены»). Пустой слот неотличим от пропущенного шага.\n')"
  [ "${legacy}" = yes ] || status=1
fi

# Унаследованную сессию не роняем дважды: если слотов нет ни одного, раздела
# условия выхода там тоже быть не может.
if [ ${#missing[@]} -ne ${#SLOTS[@]} ] && [ ${#exit_problems[@]} -gt 0 ]; then
  say "$(printf '\nУСЛОВИЕ ВЫХОДА НЕ ЗАПИСАНО (%s): %s\n' "${#exit_problems[@]}" "$(printf '«%s» ' "${exit_problems[@]}")")"
  say "$(printf 'Сессия без объявленного условия заканчивается там, где кончилось внимание.\n')"
  say "$(printf 'Условие называется В НАЧАЛЕ и проверяемо: «ревью clean и коммит», а не «поработать над фичей».\n')"
  [ "${legacy}" = yes ] || status=1
fi

if [ "${legacy}" = yes ] && [ ${#missing[@]} -gt 0 ]; then
  printf '\nСессия %s записана до %s — слотов в её шаблоне ещё не было.\n' "${latest_date}" "${ENFORCED_SINCE}"
  printf 'Прогон это не роняет: рефлексия по записанной сессии уже потеряна, и вернуть её\n'
  printf 'нельзя. Слоты появятся в следующей сессии — она пишется по текущему шаблону.\n'
fi
exit $status
