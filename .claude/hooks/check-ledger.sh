#!/bin/bash
# Ledger отвечает на «где мы сейчас», а не «что было когда».
#
# ТИР: стоп — следующая сессия начнётся с середины
#
# Замер (4 боевых проекта, 2026-08-26). Ledger — самый читаемый артефакт системы:
# 6 команд, 6 ролей, 4 гарда берут его на вход, и простой у него 0–1 день. Именно
# поэтому в него дописывают всё: в одном проекте он дорос до 3682 строк, из них
# десятки разделов вида «## Сессия <дата> — итоги», один на 1040 строк — при живом
# каталоге `project/sessions/` на 83 записи. Ledger дословно дублировал хронику.
# В другом проекте (473 строки) хроника проросла полем: «Недавно завершено» — 108
# строк, «Активные задачи» — 92.
#
# Один предмет, три его отказа:
#   1) РАЗДЕЛ-ХРОНИКА — заголовок, привязанный к дате или сессии: у событий свой
#      дом, `project/sessions/`, и там у них ротация;
#   2) ПОЛЕ ПРЕВРАТИЛОСЬ В ХРОНИКУ — поле смысла ИЛИ поле шапки длиннее предела.
#      Замер, вскрывший главное: хроника ушла в ШАПКУ, куда не смотрел ни один
#      прибор — `active_phase` 4141 символ в одном проекте, `current_omtm` 2340
#      и `current_omtm_value` 2236 в другом. Это пересказ последней сессии в поле,
#      которое обязано держать смысл. (В байтах числа вдвое больше; предел мерим
#      в символах — текстовый лимит про читаемость, а не про место на диске.);
#   3) ХРОНИКА НАКАПЛИВАЕТСЯ ПОЛЯМИ — `previous_phase_171`, `previous_phase_170`:
#      лента, отросшая нумерованными полями шапки, у которой нет дна;
#   4) ЛЕСТНИЦЫ СМЫСЛОВ НЕТ — ни одного поля «Миссия / Цель фазы / Ближайший шаг».
#      Замер: лестница приехала в 5.1 и не заведена ни в одном из четырёх боевых
#      проектов — обновление чужие ledger-ы не переписывает;
#   5) ПОТОЛОК — строк больше бюджета из шапки (`max_lines:`, умолчание 300).
#
# ЗАПУСК: bash .claude/hooks/check-ledger.sh [файл-ledger]
#   exit 0 — ledger остался состоянием (или файла нет)
#   exit 1 — есть отказ, либо разобрать файл не удалось
#
# Доказательство мутацией: .claude/hooks/check-ledger.test.sh

set -uo pipefail

LEDGER=${1:-${LEDGER_FILE:-project/ledger.md}}
MEANING_MAX=${MEANING_MAX_CHARS:-200}

[ -f "${LEDGER}" ] || { printf 'ledger не найден (%s) — проверять нечего\n' "${LEDGER}"; exit 0; }

header_lines() { awk 'NR==1 && $0!="---" {exit} NR==1 {next} /^---[[:space:]]*$/ {exit} {print}' "${LEDGER}"; }

# Бюджет строк читаем ТОЛЬКО из шапки: число в теле — это текст, а не настройка.
budget=$(header_lines | grep -m1 -E '^max_lines:' | sed -E 's/^max_lines:[[:space:]]*//; s/[^0-9].*$//')
case "${budget}" in ''|*[!0-9]*) budget=${LEDGER_MAX_LINES:-300} ;; esac

ledger_line() {  # $1 = метка поля
  grep -m1 -E "^[[:space:]]*[-*][[:space:]]*\*\*$1:\*\*" "${LEDGER}" 2>/dev/null |
    sed -E "s/^[[:space:]]*[-*][[:space:]]*\*\*$1:\*\*[[:space:]]*//; s/[[:space:]]*$//"
}

join_list() { printf '%s, ' "$@" | sed 's/, $//'; }

mission=$(ledger_line 'Миссия')
goal=$(ledger_line 'Цель фазы')
step=$(ledger_line 'Ближайший шаг')

lines=$(wc -l < "${LEDGER}" | tr -d ' ')

# Половина «найдено не ноль» стоит на РАЗБОРЕ, а не на находках: файл без шапки и
# без заголовков — не ledger, и молчание на нём читалось бы как «всё чисто».
if [ -z "$(header_lines)" ] && ! grep -qE '^#{2,3} ' "${LEDGER}"; then
  printf 'ОШИБКА: в %s нет ни шапки, ни заголовков — это не ledger.\n' "${LEDGER}" >&2
  printf 'Разобрать нечем: возьми форму из `templates/project/ledger.md`.\n' >&2
  exit 1
fi

# Заголовок-хроника: привязан к сессии или несёт дату. Ищем ЗАГОЛОВКИ, а не
# упоминания: дата внутри строки состояния законна («решено 2026-08-26»).
chronicle=$(grep -nE '^#{2,3} .*([Сс]есси|[0-9]{4}-[0-9]{2}-[0-9]{2})' "${LEDGER}" \
            | sed -E 's/^([0-9]+):#+ /строка \1: /' | cut -c1-90 || true)

long_fields=()
for pair in "Миссия:${mission}" "Цель фазы:${goal}" "Ближайший шаг:${step}"; do
  value=${pair#*:}
  [ "${#value}" -gt "${MEANING_MAX}" ] && long_fields+=("${pair%%:*} (${#value} симв.)")
done

# Поле ШАПКИ, разросшееся в пересказ сессии. Именно здесь прятался главный
# случай: в шапку не смотрел ни один прибор.
while IFS= read -r hline; do
  [ -n "${hline}" ] || continue
  name=${hline%%:*}
  [ "${#hline}" -gt "${MEANING_MAX}" ] && long_fields+=("шапка/${name} (${#hline} симв.)")
done < <(header_lines | grep -E '^[a-z_]+:')

# Лента, отросшая нумерованными полями шапки: у такой ленты нет дна.
accumulating=$(header_lines | grep -oE '^(previous_[a-z_0-9]+|phase_[0-9]+)' | tr '\n' ' ' | sed 's/ $//')

printf 'Ledger %s: строк %s при бюджете %s, предел поля смысла %s симв.\n' \
  "${LEDGER}" "${lines}" "${budget}" "${MEANING_MAX}"

failed=0

if [ -n "${chronicle}" ]; then
  printf '\nРАЗДЕЛ-ХРОНИКА В LEDGER:\n%s\n' "${chronicle}" >&2
  printf 'Ledger отвечает на «где мы сейчас». События живут в `project/sessions/` — там у них\n' >&2
  printf 'свой дом и своя ротация. Замер: в одном проекте ledger дорос до 3682 строк из таких\n' >&2
  printf 'разделов, при живом каталоге сессий на 83 записи — то есть дублировал его дословно.\n' >&2
  failed=1
fi

if [ ${#long_fields[@]} -gt 0 ]; then
  printf '\nПоле смысла превратилось в хронику (длиннее %s символов): %s.\n' \
    "${MEANING_MAX}" "$(join_list "${long_fields[@]}")" >&2
  printf 'Смысл — одна строка; события — в `session.md`. Замер: за 172 сессии поле цели фазы\n' >&2
  printf 'стало пересказом последней сессии, и цель фазы перестала существовать.\n' >&2
  failed=1
fi

if [ -n "${accumulating}" ]; then
  printf '\nХРОНИКА НАКАПЛИВАЕТСЯ ПОЛЯМИ ШАПКИ: %s.\n' "${accumulating}" >&2
  printf 'Нумерованное поле «предыдущая фаза» — это лента, у которой нет дна: следующая\n' >&2
  printf 'сессия допишет ещё одно. Прошлые фазы живут в `project/sessions/`.\n' >&2
  failed=1
fi

if [ -z "${mission}${goal}${step}" ]; then
  printf '\nЛЕСТНИЦЫ СМЫСЛОВ НЕТ: ни «Миссия», ни «Цель фазы», ни «Ближайший шаг».\n' >&2
  printf 'Заведи три строки секции «Зачем» по шаблону `templates/project/ledger.md`: без них\n' >&2
  printf 'каждая сессия начинается с середины. Замер: лестница приехала в 5.1 и не заведена\n' >&2
  printf 'ни в одном из четырёх боевых проектов — обновление чужие ledger-ы не переписывает.\n' >&2
  failed=1
fi

if [ "${lines}" -gt "${budget}" ]; then
  printf '\nПОТОЛОК ПРОБИТ: строк %s при бюджете %s.\n' "${lines}" "${budget}" >&2
  printf 'Сверни разделы состояния и увези события в `project/sessions/`. Бюджет поднимается\n' >&2
  printf 'осознанно полем `max_lines:` в шапке, а не молчаливым ростом: ёмкость есть свойство\n' >&2
  printf 'проекта. «Недавно завершено» держит только последнюю сессию — остальное уже в сессиях.\n' >&2
  failed=1
fi

[ "${failed}" -eq 0 ] || exit 1
exit 0
