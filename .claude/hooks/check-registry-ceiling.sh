#!/bin/bash
# Потолок реестра: реестр, который пополняется быстрее, чем закрывается,
#
# ТИР: счёт — реестр перерос ёмкость; это цель фазы, а не задача сессии
# перестаёт быть инструментом и становится памятником.
#
# Замер: в боевом проекте реестр дрейфа дошёл до 76 открытых записей против
# 32 закрытых и рос на 12 за одну сессию. В него перестают смотреть, потому что
# смотреть больше не на что — там всё.
#
# Потолок берётся из шапки самого реестра (`ceiling:`), а не из этого скрипта:
# ёмкость — свойство проекта, а не фреймворка.
#
# ЗАПУСК: bash .claude/hooks/check-registry-ceiling.sh [файл-реестр]
#   exit 0 — открытых записей не больше потолка (или реестра нет)
#   exit 1 — потолок пробит, либо разобрать реестр не удалось
#
# Доказательство мутацией: .claude/hooks/check-registry-ceiling.test.sh

set -uo pipefail

REGISTRY=${1:-${REGISTRY_FILE:-project/artifacts/drift-registry.md}}

[ -f "${REGISTRY}" ] || { printf 'реестра нет (%s) — проверять нечего\n' "${REGISTRY}"; exit 0; }

# Потолок читаем ТОЛЬКО из шапки: число, встреченное в теле, — это текст, не настройка.
ceiling=$(awk 'NR==1 && $0!="---" {exit} NR==1 {next} /^---[[:space:]]*$/ {exit} {print}' "${REGISTRY}" \
          | grep -m1 -E '^ceiling:' | sed -E 's/^ceiling:[[:space:]]*//; s/[^0-9].*$//')

case "${ceiling}" in
  ''|*[!0-9]*)
    printf 'ОШИБКА: в шапке %s нет числового поля ceiling.\n' "${REGISTRY}" >&2
    printf 'Реестр без объявленной ёмкости растёт молча — это и есть механизм памятника.\n' >&2
    exit 1
    ;;
esac

# Записи считаем по строкам таблицы с идентификатором, а не по всем строкам таблицы:
# заголовок и разделитель записями не являются.
count_rows() {  # $1 = имя раздела
  awk -v want="## $1" '
    $0 == want {inside=1; next}
    /^## / {inside=0}
    inside && /^\|/ {print}
  ' "${REGISTRY}" | grep -cE '^\|[[:space:]]*\**[A-Z]+-[0-9]+' || true
}

open_rows=$(count_rows 'Открытые')
closed_rows=$(count_rows 'Закрытые')

# Половина «найдено не ноль»: раздел «Открытые» есть, а разобрано ноль строк —
# это отказ разбора, а не пустой реестр. Молчаливый ноль читается как «всё чисто».
if ! grep -qE '^## Открытые' "${REGISTRY}"; then
  printf 'ОШИБКА: в %s нет раздела «Открытые» — разобрать реестр нечем.\n' "${REGISTRY}" >&2
  exit 1
fi

printf 'Реестр %s: открытых %s, закрытых %s, потолок %s.\n' \
  "${REGISTRY}" "${open_rows}" "${closed_rows}" "${ceiling}"

if [ "${open_rows}" -gt "${ceiling}" ]; then
  printf '\nПОТОЛОК ПРОБИТ: открытых %s при потолке %s.\n' "${open_rows}" "${ceiling}" >&2
  printf 'Новая находка теперь не дописывается молча. Одно из двух, явно:\n' >&2
  printf '  1) вытесняет запись ниже приоритетом — и та ЗАКРЫВАЕТСЯ решением «не чиним»;\n' >&2
  printf '  2) цель фазы меняется на «закрыть реестр до потолка» и пишется в ledger.\n' >&2
  exit 1
fi
exit 0
