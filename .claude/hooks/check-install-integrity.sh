#!/bin/bash
# Целостность развёрнутой копии: доехал ли инструмент рабочим, а не просто файлами.
#
# ТИР: копия — про развёрнутую копию, а не про проект
#
# Замер, из которого выросла проверка: три класса дрейфа, найденные вручную,
# и все три — «объявлено ≠ подключено»:
#   · `VERSION` лежал в корне и не попадал в `.claude/` — потребитель не получал
#     его никогда, хотя CLAUDE.md обещал;
#   · `hooks.json` выглядел конфигом хуков и им не был;
#   · имена слотов в шаблоне сессии и в проверщике рефлексии живут в РАЗНЫХ
#     файлах, и разъехаться они могут молча.
# Плюс трижды за один MR устаревало число случаев, заявленное в документации.
#
# ЗАПУСК: bash .claude/hooks/check-install-integrity.sh [корень копии]
#   exit 0 — копия работоспособна
#   exit 1 — что-то объявлено и не подключено, либо проверять оказалось нечего
#
# Доказательство мутацией: .claude/hooks/check-install-integrity.test.sh

set -uo pipefail

ROOT=${1:-.}
CLAUDE_DIR="${ROOT}/.claude"

problems=()
checked=0

word_to_number() {  # $1 = числительное словом; печатает 0, если слово незнакомо
  case "$1" in
    один|одна) printf '1' ;; два|две) printf '2' ;; три) printf '3' ;; четыре) printf '4' ;;
    пять) printf '5' ;; шесть) printf '6' ;; семь) printf '7' ;; восемь) printf '8' ;;
    девять) printf '9' ;; десять) printf '10' ;; одиннадцать) printf '11' ;;
    двенадцать) printf '12' ;; тринадцать) printf '13' ;; четырнадцать) printf '14' ;;
    пятнадцать) printf '15' ;; шестнадцать) printf '16' ;; семнадцать) printf '17' ;;
    восемнадцать) printf '18' ;; девятнадцать) printf '19' ;; двадцать) printf '20' ;;
    *) printf '0' ;;
  esac
}

note() { problems+=("$1"); }

[ -d "${CLAUDE_DIR}" ] || { printf 'ОШИБКА: нет %s — это не развёрнутая копия фреймворка.\n' "${CLAUDE_DIR}" >&2; exit 1; }

# --- 1. Версия едет вместе с инструментом -----------------------------------
checked=$((checked + 1))
if [ ! -s "${CLAUDE_DIR}/VERSION" ]; then
  note "нет ${CLAUDE_DIR}/VERSION — CLAUDE.md обещает версию именно там"
fi

# --- 2. Хуки исполняемы -----------------------------------------------------
shopt -s nullglob
hooks=("${CLAUDE_DIR}"/hooks/*.sh)
if [ "${#hooks[@]}" -eq 0 ]; then
  printf 'ОШИБКА: в %s/hooks не найдено ни одного скрипта.\n' "${CLAUDE_DIR}" >&2
  printf 'Перечисляющая проверка на пустом множестве проходит по построению — считаем отказом.\n' >&2
  exit 1
fi
for hook in "${hooks[@]}"; do
  checked=$((checked + 1))
  [ -x "${hook}" ] || note "не исполняем: ${hook}"
done

# --- 3. Объявленные хуки существуют ------------------------------------------
settings="${CLAUDE_DIR}/settings.json"
if [ ! -f "${settings}" ]; then
  note "нет ${settings} — событийные хуки не объявлены, значит не вызываются"
elif command -v jq >/dev/null 2>&1; then
  if ! jq -e 'type == "object"' "${settings}" >/dev/null 2>&1; then
    note "${settings} не разбирается как объект"
  else
    declared=0
    while IFS= read -r command_line; do
      [ -n "${command_line}" ] || continue
      declared=$((declared + 1))
      checked=$((checked + 1))
      target=${command_line%% *}
      # Путь ищем ТОЛЬКО внутри проверяемой копии. Запасной поиск относительно
      # текущего каталога давал ложно-зелёное: файл соседней установки
      # удовлетворял проверке копии, в которой его нет.
      case "${target}" in
        /*) [ -f "${target}" ] || note "хук объявлен, файла нет: ${target}" ;;
        *)  [ -f "${ROOT}/${target}" ] || note "хук объявлен, файла нет: ${target}" ;;
      esac
    done < <(jq -r '.hooks // {} | to_entries[] | .value[]? | .hooks[]? | .command // empty' "${settings}" 2>/dev/null)
    [ "${declared}" -gt 0 ] || note "в ${settings} нет ни одного объявленного хука — «файл лежит» ≠ «хук вызывается»"
  fi
fi

# --- 4. Слоты шаблона сессии ↔ слоты проверщика рефлексии --------------------
template="${CLAUDE_DIR}/templates/project/session-template.md"
checker="${CLAUDE_DIR}/hooks/check-session-reflection.sh"
if [ -f "${template}" ] && [ -f "${checker}" ]; then
  slots=$(grep -m1 '^SLOTS=(' "${checker}" | sed -E "s/^SLOTS=\(//; s/\)$//; s/' '/\n/g; s/'//g")
  if [ -z "${slots}" ]; then
    note "не удалось прочитать список слотов из ${checker}"
  else
    while IFS= read -r slot; do
      [ -n "${slot}" ] || continue
      checked=$((checked + 1))
      grep -qF -- "${slot}" "${template}" || note "проверщик ждёт слот «${slot}», в шаблоне сессии его нет"
    done <<< "${slots}"
  fi
fi

# --- 5. Навыки, объявленные ролями, существуют ------------------------------
# `skills:` вливает содержимое навыка в контекст роли при старте. Объявленный
# и отсутствующий навык — это роль, которая молча стартует без своего ремесла.
for role_file in "${CLAUDE_DIR}"/agents/*.md; do
  skills_line=$(grep -m1 '^skills:' "${role_file}" 2>/dev/null)
  [ -n "${skills_line}" ] || continue
  names=$(printf '%s' "${skills_line}" | sed -E 's/^skills:[[:space:]]*\[([^]]*)\].*/\1/' | tr ',' ' ')
  for name in ${names}; do
    name=$(printf '%s' "${name}" | tr -d '"'"'"' ')
    [ -n "${name}" ] || continue
    checked=$((checked + 1))
    [ -f "${CLAUDE_DIR}/skills/${name}/SKILL.md" ] \
      || note "$(basename "${role_file}") объявляет навык «${name}», в копии его нет"
  done
done

# --- 6. Ремесло роли (DPF) доехало ------------------------------------------
# Замер по четырём боевым проектам: в одном (94 сессии, 11 ролей) DPF отсутствует
# ЦЕЛИКОМ — копия обновлена с версии до 5.0, а слой ремесла приходит только на
# Шаге 4b `/setup-project` и повторно не заводится. В другом имплантированная роль
# получила проектный оверлей без базового ремесла: активационный ритуал читает пустоту.
if [ -d "${CLAUDE_DIR}/agents" ]; then
  if [ ! -d "${CLAUDE_DIR}/knowledge/dpf" ]; then
    note "слоя DPF нет вовсе (${CLAUDE_DIR}/knowledge/dpf) — ролям нечего читать в активационном ритуале"
  else
    for role_file in "${CLAUDE_DIR}"/agents/*.md; do
      [ -f "${role_file}" ] || continue
      checked=$((checked + 1))
      craft=$(grep -m1 -oE 'knowledge/dpf/[a-z-]+\.md' "${role_file}" | sed 's|knowledge/dpf/||')
      if [ -z "${craft}" ]; then
        note "$(basename "${role_file}") не называет свой DPF — шаг ритуала «прочитай ремесло» пуст"
      elif [ ! -f "${CLAUDE_DIR}/knowledge/dpf/${craft}" ]; then
        note "$(basename "${role_file}") ссылается на ремесло ${craft}, файла нет"
      fi
    done
  fi
fi

# --- 7. Правила с путями ведут в существующие файлы -------------------------
# Правило — триггер, а не копия: оно указывает, что прочитать. Указатель в никуда
# хуже отсутствующего правила: роль думает, что справочник есть.
for rule_file in "${CLAUDE_DIR}"/rules/*.md; do
  [ -f "${rule_file}" ] || continue
  while IFS= read -r target; do
    [ -n "${target}" ] || continue
    checked=$((checked + 1))
    [ -e "${ROOT}/${target}" ] \
      || note "правило $(basename "${rule_file}") ведёт в несуществующий ${target}"
    # Читаем ТОЛЬКО тело правила: в шапке живут глобы `paths:`, и они не ссылки.
    # Класс «не пробел и не кавычка», а не список латинских букв: путь с кириллицей
    # в имени иначе обрезался до каталога, и указатель в никуда проходил.
    # Глобы отбрасываем и в теле — `knowledge/**` файлом быть не обязан.
  done < <(awk 'NR==1 && $0=="---" {inhead=1; next} inhead && /^---[[:space:]]*$/ {inhead=0; next} !inhead' "${rule_file}" \
           | grep -ohE '\.claude/(knowledge|skills)/[^[:space:]`"'"'"',;)]+' \
           | sed -E 's/[.,;:)]+$//' | grep -v '[*?]' | sort -u)
done

# --- 8. Заявленное число случаев ↔ фактическое ------------------------------
# Класс, случившийся трижды за один MR: набор растёт, число в документации нет.
claude_md="${CLAUDE_DIR}/CLAUDE.md"

# Набор живёт либо у ядра (`hooks/`), либо у плагина (`plugins/*/scripts/`).
# Искать только в первом месте значит не сверять числа плагинов ВОВСЕ — и
# промолчать об этом: заявленное «25 случаев» осталось бы мнением автора.
suite_path() {  # $1 = имя файла набора → путь или пусто
  local candidate
  candidate="${CLAUDE_DIR}/hooks/$1"
  [ -f "${candidate}" ] && { printf '%s' "${candidate}"; return 0; }
  for candidate in "${CLAUDE_DIR}"/../plugins/*/scripts/"$1"; do
    [ -f "${candidate}" ] && { printf '%s' "${candidate}"; return 0; }
  done
  return 0
}

# Ядро рассказывает и о плагинах — их приборы и наборы описаны здесь же. Но в
# копии потребителя плагинов может не быть: они ставятся отдельно и живут вне
# `.claude/`. Требовать их файлы значит объявлять исправную копию неработоспособной.
# Замер: чистая установка ядра без плагинов дала «КОПИЯ НЕ РАБОТОСПОСОБНА (2)» —
# оба пункта про `check-scenario-coverage.test.sh`, который приезжает с `product-loop`.
#
# Признак принадлежности — не имя и не место упоминания, а СВОЙ ПРИБОР рядом:
# у набора ядра он лежит в `hooks/`. Потерянный набор ядра прибор переживёт и
# останется находкой; отсутствующий плагин не оставляет ни того, ни другого.
suite_is_core() {  # $1 = имя файла набора
  [ -f "${CLAUDE_DIR}/hooks/${1%.test.sh}.sh" ]
}
if [ -f "${claude_md}" ]; then
  while IFS='|' read -r suite claimed; do
    [ -n "${suite}" ] || continue
    checked=$((checked + 1))
    path=$(suite_path "${suite}")
    if [ -z "${path}" ] && ! suite_is_core "${suite}"; then
      # Инструмент со стороны, в этой копии не установлен — не предмет ядра.
      checked=$((checked - 1))
      continue
    fi
    actual=$(grep -m1 '^EXPECTED_CASES=' "${path}" 2>/dev/null | cut -d= -f2)
    if [ -z "${actual}" ]; then
      note "в документации назван набор ${suite}, а файла или его счётчика нет"
    elif [ "${actual}" != "${claimed}" ]; then
      note "${suite}: документация говорит ${claimed} случаев, в наборе ${actual}"
    fi
  done < <(grep -oE '`[a-z-]+\.test\.sh` \([0-9]+ случа' "${claude_md}" \
           | sed -E 's/`([a-z-]+\.test\.sh)` \(([0-9]+) случа/\1|\2/')

  # Числа МУТАЦИЙ доказательством не являются — их нельзя пересчитать прогоном.
  # Но расходиться с записью автора они не должны: класс «набор вырос, число
  # в документации нет» случился трижды за один MR именно на числах случаев.
  # Поэтому набор объявляет `MUTATIONS=` рядом с `EXPECTED_CASES=`, а здесь сверяется.
  while IFS='|' read -r suite claimed_m; do
    [ -n "${suite}" ] || continue
    checked=$((checked + 1))
    path=$(suite_path "${suite}")
    if [ -z "${path}" ] && ! suite_is_core "${suite}"; then
      checked=$((checked - 1))
      continue
    fi
    actual_m=$(grep -m1 '^MUTATIONS=' "${path}" 2>/dev/null | cut -d= -f2 | tr -cd '0-9')
    if [ -z "${actual_m}" ]; then
      note "набор ${suite} не объявляет MUTATIONS, а документация называет число"
    elif [ "${actual_m}" != "${claimed_m}" ]; then
      note "${suite}: документация говорит ${claimed_m} мутаций, в наборе объявлено ${actual_m}"
    fi
  done < <(
    # Без awk: линт CI запрещает трёхаргументный match(), а regex с запятой внутри
    # ловится и двухаргументный — прибор не должен спотыкаться о собственный линт.
    grep -oE '`[a-z-]+\.test\.sh` \([0-9]+ [^,]+, [^ ]+ мутаци' "${claude_md}" 2>/dev/null \
    | while IFS= read -r chunk; do
        suite=$(printf '%s' "${chunk}" | sed -E 's/^`([a-z-]+\.test\.sh)`.*/\1/')
        # `[а-я]` зависит от локали: в `C` GNU трактует класс побайтово и
        # захватывает лишнее. Берём «слово между запятой и словом мутаци» через
        # отрицание ASCII-символов — оно байтово-безопасно в любой локали.
        word=$(printf '%s' "${chunk}" | sed -E 's/.*, ([^ ]+) мутаци.*/\1/')
        num=$(word_to_number "${word}")
        [ "${num}" -gt 0 ] && printf '%s|%s\n' "${suite}" "${num}"
      done
  )
fi

# --- 9. Сущности, названные в CLAUDE.md, определены в словаре ----------------
# Класс: короткая таблица признаков живёт в CLAUDE.md (она всегда в контексте),
# полные определения — в knowledge/entities.md. Два описания одного предмета
# расходятся молча, и роль начинает применять признак, которого больше нет.
entities="${CLAUDE_DIR}/knowledge/entities.md"
if grep -q '^## Сущности' "${claude_md}" 2>/dev/null; then
  checked=$((checked + 1))
  if [ ! -f "${entities}" ]; then
    note "CLAUDE.md объявляет раздел «Сущности», а knowledge/entities.md нет"
  else
    named=0
    # Имена берём из ПЕРВОЙ колонки таблицы признаков и только из неё: жирное
    # начертание в тексте раздела сущностью не является.
    while IFS= read -r term; do
      [ -n "${term}" ] || continue
      named=$((named + 1))
      grep -qE "^## ${term}\$" "${entities}" \
        || note "сущность «${term}» названа в CLAUDE.md, а раздела «## ${term}» в entities.md нет"
    done < <(awk '/^## Сущности/{t=1; next} t && /^## /{t=0} t && /^\| \*\*/ {print}' "${claude_md}" \
             | sed -E 's/^\| \*\*([^*]+)\*\*.*/\1/')
    # Половина «найдено не ноль»: раздел есть, а сущностей в нём ноль — это
    # съехавшая разметка таблицы, а не отсутствие сущностей.
    [ "${named}" -gt 0 ] || note "раздел «Сущности» в CLAUDE.md есть, а ни одной сущности в таблице не разобрано"
  fi
fi

# --- 10. Одна спецификация блока памяти на файл роли -------------------------
# Класс, найденный в пяти файлах ролей сразу: рядом лежали ДВА описания одного
# блока, и второе просило «Что сделано» — то есть ровно хронику, которую первое
# запрещает и которую блокирует memory-gate. Роль получала противоречие в одном
# файле. Заодно ловим непарное ограждение кода: у устаревшего блока оставалась
# висячая ``` и разметка ниже читалась как код.
specs=0
if [ -d "${CLAUDE_DIR}/agents" ]; then
  for role_file in "${CLAUDE_DIR}"/agents/*.md; do
    [ -f "${role_file}" ] || continue
    checked=$((checked + 1))
    blocks=$(grep -c '^## Для памяти роли' "${role_file}" || true)
    specs=$((specs + blocks))
    [ "${blocks}" -le 1 ] \
      || note "$(basename "${role_file}"): описаний блока памяти ${blocks} — роль получает противоречие в одном файле"
    fences=$(grep -c '^```' "${role_file}" || true)
    [ $((fences % 2)) -eq 0 ] \
      || note "$(basename "${role_file}"): непарное ограждение кода (${fences}) — разметка ниже читается как код"
  done
  # Половина «найдено не ноль»: файлы ролей есть, а спецификации блока памяти нет
  # ни в одном — значит память ролей не пополнится, и заметить это будет нечем.
  if [ "${checked}" -gt 0 ] && [ "${specs}" -eq 0 ]; then
    note "файлы ролей есть, а описания блока «Для памяти роли» нет ни в одном"
  fi
fi

# --- 10a. Маршрут ведёт к роли, которая есть ---------------------------------
# Протоколы маршрутизируют tension по домену: «Рисковая → Guardian», «Чёрная →
# Guardian». Имя роли, которой в копии нет, маршрутом не является — tension уходит
# в никуда и возвращается неразобранным. Замер: три роли боевого проекта (Growth,
# Brand, CFO) переехали в общие протоколы вместе с текстом и остались там после
# того, как состав ролей фреймворка устоялся на одиннадцати.
#
# Смотрим только адресатов маршрутов: правый столбец таблицы шляп и хвост строки
# после `→`. Проза и примеры чужих команд (`guide-multi-agent-teams.md` описывает,
# как собрать СВОЮ команду) под правило не подпадают.
protocols="${CLAUDE_DIR}/knowledge/core-protocols.md"
if [ -f "${protocols}" ]; then
  known=$(
    { ls "${CLAUDE_DIR}"/agents/*.md 2>/dev/null
      ls "${CLAUDE_DIR}"/templates/roles/optional/*.md 2>/dev/null
    } | while IFS= read -r f; do basename "${f}" .md; done | tr 'A-Z' 'a-z'
  )
  # Строка-заголовок таблицы («| Вариант | Плюсы | Минусы |») адресатом не является:
  # опознаётся по следующей строке-разделителю. Без этого прибор объявлял «Минусы»
  # ролью, которой нет.
  addressees=$(
    { awk 'NR > 1 { if (prev ~ /^\|/ && $0 !~ /^\|[[:space:]:-]+\|/) print prev } { prev = $0 } END { if (prev ~ /^\|/) print prev }' "${protocols}" \
        | grep -oE '^\|[^|]*\|[^|]*\|[[:space:]]*[A-ZА-Я][A-Za-zА-Яа-я]+([[:space:]]*/[[:space:]]*[A-ZА-Я][A-Za-zА-Яа-я]+)?[[:space:]]*\|' \
        | sed -E 's/^\|[^|]*\|[^|]*\|//; s/\|$//'
      grep -oE '→[[:space:]]*[A-ZА-Я][A-Za-zА-Яа-я]+([[:space:]]*\+[[:space:]]*[A-ZА-Я][A-Za-zА-Яа-я]+)?' "${protocols}" \
        | sed -E 's/^→[[:space:]]*//'
    } | tr '/+' '\n' | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//' | tr 'A-Z' 'a-z' | sort -u
  )
  while IFS= read -r who; do
    [ -n "${who}" ] || continue
    case "${who}" in ''|fix|guard|prove|document) continue ;; esac
    checked=$((checked + 1))
    printf '%s\n' "${known}" | grep -qx "${who}" \
      || note "core-protocols.md: маршрут ведёт к роли «${who}», которой в копии нет — tension уйдёт в никуда"
  done <<< "${addressees}"
fi

# --- 10b. Бриф не заказывает хронику -----------------------------------------
# Тот же предмет с другой стороны. Проверка выше смотрит файлы ролей, а в момент
# работы сильнее файла роли оказывается БРИФ: он и есть сообщение агенту. Замер:
# форма брифа просила «Для памяти роли: дата, что сделано, решения, следующий шаг»,
# то есть ровно ленту, которую гейт 12 запрещает, `memory-gate.sh` блокирует, а
# канон блока в файле роли заменяет срезом состояния. Правило действовало в одном
# месте из двух, и то, что доезжает до роли, было вторым.
brief="${CLAUDE_DIR}/templates/dispatch-brief.md"
if [ -f "${brief}" ]; then
  checked=$((checked + 1))
  # Смотрим ТОЛЬКО форму — текст внутри ограждения кода, который копируется в
  # сообщение агенту. Проза ниже разбирает этот самый дефект и цитирует его;
  # прибор, ищущий по всему файлу, находил бы собственное объяснение. Класс уже
  # известен: детектор непереносимых форм тоже находил сам себя, пока образец не
  # стали собирать на лету.
  form=$(awk '/^```$/ {inside = !inside; next} inside {print}' "${brief}")
  # Отрицание — не требование. Строка «Не «что сделано за сессию»» ЗАПРЕЩАЕТ хронику,
  # и прибор, ищущий подстроку, принимал запрет за заказ. Ищем строки с «что сделано»,
  # у которых нет отрицания перед ним.
  if printf '%s' "${form}" | grep -q 'Для памяти роли' \
     && printf '%s' "${form}" | grep -i 'что сделано' | grep -qvi '[Нн]е .что сделано\|а не .что сделано'; then
    note "dispatch-brief.md: форма брифа заказывает хронику («что сделано») там, где канон роли требует срез состояния"
  fi
  # Гейт 5 применяется ровно здесь: бриф — единственное место, где модель называется.
  checked=$((checked + 1))
  printf '%s' "${form}" | grep -qi 'МОДЕЛЬ\.' \
    || note "dispatch-brief.md: в форме брифа нет поля модели — гейт «явный выбор модели» негде исполнить"
fi

# --- 11. Каждый прибор объявляет свой тир -----------------------------------
# Класс: 19 приборов и одно слово «ОБЯЗАТЕЛЬНО» на всех — внимание уходит к самой
# громкой находке, а не к самой дорогой. Тир объявляется строкой `# ТИР:` в самом
# приборе; прибор без тира в сводку `check-findings-budget.sh` не попадает, то есть
# его находки исчезают из порядка молча.
tiered=0
if [ -d "${CLAUDE_DIR}/hooks" ]; then
  for tool in "${CLAUDE_DIR}"/hooks/*.sh; do
    # Наборы проверок и библиотеки приборами не являются: у первых предмет —
    # доказательство, у вторых — общий код, и тира ни у тех, ни у других нет.
    case "$(basename "${tool}")" in *.test.sh|lib-*.sh) continue ;; esac
    [ -f "${tool}" ] || continue
    checked=$((checked + 1))
    declared=$(grep -m1 '^# ТИР:' "${tool}" | sed -E 's/^# ТИР:[[:space:]]*//; s/[[:space:]]*—.*$//')
    if [ -z "${declared}" ]; then
      note "$(basename "${tool}"): тир не объявлен — находки выпадут из сводки молча; если это остаток прежней версии (наложение не удаляет), файл надо убрать"
    else
      tiered=$((tiered + 1))
      case "${declared}" in
        стоп|счёт|копия|волна|показ|сводка) ;;
        *) note "$(basename "${tool}"): тир «${declared}» не из набора (стоп/счёт/копия/волна/показ/сводка)" ;;
      esac
    fi
  done
  # Половина «найдено не ноль»: приборы есть, а тир не объявлен ни у одного —
  # значит сводка пуста, и порядок по ставке не работает вовсе.
  if [ "${tiered}" -eq 0 ]; then
    note "приборы есть, а тир не объявлен ни у одного — сводка находок пуста"
  fi
fi

printf 'Проверено пунктов: %s. Расхождений: %s.\n' "${checked}" "${#problems[@]}"
[ "${#problems[@]}" -eq 0 ] && exit 0

printf '\nКОПИЯ НЕ РАБОТОСПОСОБНА (%s):\n' "${#problems[@]}" >&2
printf '  %s\n' "${problems[@]}" >&2
exit 1
