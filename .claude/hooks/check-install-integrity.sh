#!/bin/bash
# Целостность развёрнутой копии: доехал ли инструмент рабочим, а не просто файлами.
#
# ТИР: копия — про развёрнутую копию, а не про проект
#
# Замер, из которого выросла проверка: три класса дрейфа, найденные вручную,
# и все три — «объявлено ≠ подключено»:
#   · `VERSION` лежал в корне и не попадал в `.claude/` — потребитель не получал
#     его никогда, хотя CLAUDE.md обещал;
#   · `hooks.json` выглядел конфигом хуков и им не был;
#   · имена слотов в шаблоне сессии и в проверщике рефлексии живут в РАЗНЫХ
#     файлах, и разъехаться они могут молча.
# Плюс трижды за один MR устаревало число случаев, заявленное в документации.
#
# ЗАПУСК: bash .claude/hooks/check-install-integrity.sh [корень копии]
#   exit 0 — копия работоспособна
#   exit 1 — что-то объявлено и не подключено, либо проверять оказалось нечего
#
# Доказательство мутацией: .claude/hooks/check-install-integrity.test.sh

set -uo pipefail

ROOT=${1:-.}
CLAUDE_DIR="${ROOT}/.claude"

problems=()
checked=0

# Путь, названный в одном месте, ищется в другом ПО ГРАНИЦЕ, а не по имени файла.
# Замер ревью 5.3.2: сверка по `basename` засчитывала `project/docs/other/README.md`
# как исполнение обещания про `project/secrets/README.md` — одноимённые файлы в
# разных каталогах для проекта норма (`README.md`, `context.md`), и подмена пути
# проходила зелёной. Совпадение обязано начинаться на границе: начало строки,
# слэш, обратная кавычка или пробел.
mentions_path() {  # $1 = текст, $2 = путь (можно с каталогами)
  local needle bounds_before bounds_after
  needle=$(printf '%s' "$2" | sed -E 's/[.[\*^$()+?{}|]/\\&/g')
  # Сопоставление средствами оболочки, а не конвейером: `printf … | grep -q` под
  # `set -o pipefail` даёт ЛОЖНУЮ находку, когда grep выходит по первому совпадению
  # раньше, чем printf допишет вход, — printf получает SIGPIPE, и статус конвейера
  # становится ненулевым. Замер: CI на Linux упал одной находкой
  # («facilitator.md не называет backlog.md») там, где macOS был зелёным: вход там
  # целый файл роли, и гонка воспроизводится только на достаточно большом.
  bounds_before='(^|[/`[:space:]"'"'"'(])'
  bounds_after='([[:space:]`,.;)]|$)'
  [[ "$1" =~ ${bounds_before}${needle}${bounds_after} ]]
}

# Разбор шапки вынесен в библиотеку: комментарий после значения оставался частью
# значения, а шаблоны фреймворка комментируют почти каждое поле. Сломанная
# библиотека проверку не роняет — есть запасной путь.
_lib_fm="$(cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null && pwd)/lib-frontmatter.sh"
if [ -f "${_lib_fm}" ]; then
  # shellcheck source=/dev/null
  . "${_lib_fm}"
  fm_value() { fm_field "$1" "$2"; }
else
  fm_value() {  # $1 = файл, $2 = поле шапки
    awk 'NR==1 && $0!="---" {exit} NR==1 {next} /^---[[:space:]]*$/ {exit} {print}' "$1" 2>/dev/null \
      | grep -m1 -E "^$2:" | sed -E "s/^$2:[[:space:]]*//; s/^\"//; s/\"[[:space:]]*$//"
  }
fi

word_to_number() {  # $1 = числительное словом; печатает 0, если слово незнакомо
  case "$1" in
    один|одна) printf '1' ;; два|две) printf '2' ;; три) printf '3' ;; четыре) printf '4' ;;
    пять) printf '5' ;; шесть) printf '6' ;; семь) printf '7' ;; восемь) printf '8' ;;
    девять) printf '9' ;; десять) printf '10' ;; одиннадцать) printf '11' ;;
    двенадцать) printf '12' ;; тринадцать) printf '13' ;; четырнадцать) printf '14' ;;
    пятнадцать) printf '15' ;; шестнадцать) printf '16' ;; семнадцать) printf '17' ;;
    восемнадцать) printf '18' ;; девятнадцать) printf '19' ;; двадцать) printf '20' ;;
    *) printf '0' ;;
  esac
}

note() { problems+=("$1"); }

[ -d "${CLAUDE_DIR}" ] || { printf 'ОШИБКА: нет %s — это не развёрнутая копия фреймворка.\n' "${CLAUDE_DIR}" >&2; exit 1; }

# --- 1. Версия едет вместе с инструментом -----------------------------------
checked=$((checked + 1))
if [ ! -s "${CLAUDE_DIR}/VERSION" ]; then
  note "нет ${CLAUDE_DIR}/VERSION — CLAUDE.md обещает версию именно там"
fi

# --- 2. Хуки исполняемы -----------------------------------------------------
shopt -s nullglob
hooks=("${CLAUDE_DIR}"/hooks/*.sh)
if [ "${#hooks[@]}" -eq 0 ]; then
  printf 'ОШИБКА: в %s/hooks не найдено ни одного скрипта.\n' "${CLAUDE_DIR}" >&2
  printf 'Перечисляющая проверка на пустом множестве проходит по построению — считаем отказом.\n' >&2
  exit 1
fi
for hook in "${hooks[@]}"; do
  checked=$((checked + 1))
  [ -x "${hook}" ] || note "не исполняем: ${hook}"
done

# --- 3. Объявленные хуки существуют ------------------------------------------
settings="${CLAUDE_DIR}/settings.json"
if [ ! -f "${settings}" ]; then
  note "нет ${settings} — событийные хуки не объявлены, значит не вызываются"
elif command -v jq >/dev/null 2>&1; then
  if ! jq -e 'type == "object"' "${settings}" >/dev/null 2>&1; then
    note "${settings} не разбирается как объект"
  else
    declared=0
    while IFS= read -r command_line; do
      [ -n "${command_line}" ] || continue
      declared=$((declared + 1))
      checked=$((checked + 1))
      target=${command_line%% *}
      # Путь ищем ТОЛЬКО внутри проверяемой копии. Запасной поиск относительно
      # текущего каталога давал ложно-зелёное: файл соседней установки
      # удовлетворял проверке копии, в которой его нет.
      case "${target}" in
        /*) [ -f "${target}" ] || note "хук объявлен, файла нет: ${target}" ;;
        *)  [ -f "${ROOT}/${target}" ] || note "хук объявлен, файла нет: ${target}" ;;
      esac
    done < <(jq -r '.hooks // {} | to_entries[] | .value[]? | .hooks[]? | .command // empty' "${settings}" 2>/dev/null)
    [ "${declared}" -gt 0 ] || note "в ${settings} нет ни одного объявленного хука — «файл лежит» ≠ «хук вызывается»"
  fi
fi

# --- 4. Слоты шаблона сессии ↔ слоты проверщика рефлексии --------------------
template="${CLAUDE_DIR}/templates/project/session-template.md"
checker="${CLAUDE_DIR}/hooks/check-session-reflection.sh"
if [ -f "${template}" ] && [ -f "${checker}" ]; then
  slots=$(grep -m1 '^SLOTS=(' "${checker}" | sed -E "s/^SLOTS=\(//; s/\)$//; s/' '/\n/g; s/'//g")
  if [ -z "${slots}" ]; then
    note "не удалось прочитать список слотов из ${checker}"
  else
    while IFS= read -r slot; do
      [ -n "${slot}" ] || continue
      checked=$((checked + 1))
      grep -qF -- "${slot}" "${template}" || note "проверщик ждёт слот «${slot}», в шаблоне сессии его нет"
    done <<< "${slots}"
  fi
fi

# --- 5. Навыки, объявленные ролями, существуют ------------------------------
# `skills:` вливает содержимое навыка в контекст роли при старте. Объявленный
# и отсутствующий навык — это роль, которая молча стартует без своего ремесла.
for role_file in "${CLAUDE_DIR}"/agents/*.md; do
  skills_line=$(grep -m1 '^skills:' "${role_file}" 2>/dev/null)
  [ -n "${skills_line}" ] || continue
  names=$(printf '%s' "${skills_line}" | sed -E 's/^skills:[[:space:]]*\[([^]]*)\].*/\1/' | tr ',' ' ')
  for name in ${names}; do
    name=$(printf '%s' "${name}" | tr -d '"'"'"' ')
    [ -n "${name}" ] || continue
    checked=$((checked + 1))
    [ -f "${CLAUDE_DIR}/skills/${name}/SKILL.md" ] \
      || note "$(basename "${role_file}") объявляет навык «${name}», в копии его нет"
  done
done

# --- 6. Ремесло роли (DPF) доехало ------------------------------------------
# Замер по четырём боевым проектам: в одном (94 сессии, 11 ролей) DPF отсутствует
# ЦЕЛИКОМ — копия обновлена с версии до 5.0, а слой ремесла приходит только на
# Шаге 4b `/setup-project` и повторно не заводится. В другом имплантированная роль
# получила проектный оверлей без базового ремесла: активационный ритуал читает пустоту.
if [ -d "${CLAUDE_DIR}/agents" ]; then
  if [ ! -d "${CLAUDE_DIR}/knowledge/dpf" ]; then
    note "слоя DPF нет вовсе (${CLAUDE_DIR}/knowledge/dpf) — ролям нечего читать в активационном ритуале"
  else
    for role_file in "${CLAUDE_DIR}"/agents/*.md; do
      [ -f "${role_file}" ] || continue
      checked=$((checked + 1))
      craft=$(grep -m1 -oE 'knowledge/dpf/[a-z-]+\.md' "${role_file}" | sed 's|knowledge/dpf/||')
      if [ -z "${craft}" ]; then
        note "$(basename "${role_file}") не называет свой DPF — шаг ритуала «прочитай ремесло» пуст"
      elif [ ! -f "${CLAUDE_DIR}/knowledge/dpf/${craft}" ]; then
        note "$(basename "${role_file}") ссылается на ремесло ${craft}, файла нет"
      fi
    done
  fi
fi

# --- 7. Правила с путями ведут в существующие файлы -------------------------
# Правило — триггер, а не копия: оно указывает, что прочитать. Указатель в никуда
# хуже отсутствующего правила: роль думает, что справочник есть.
for rule_file in "${CLAUDE_DIR}"/rules/*.md; do
  [ -f "${rule_file}" ] || continue
  while IFS= read -r target; do
    [ -n "${target}" ] || continue
    checked=$((checked + 1))
    [ -e "${ROOT}/${target}" ] \
      || note "правило $(basename "${rule_file}") ведёт в несуществующий ${target}"
    # Читаем ТОЛЬКО тело правила: в шапке живут глобы `paths:`, и они не ссылки.
    # Класс «не пробел и не кавычка», а не список латинских букв: путь с кириллицей
    # в имени иначе обрезался до каталога, и указатель в никуда проходил.
    # Глобы отбрасываем и в теле — `knowledge/**` файлом быть не обязан.
  done < <(awk 'NR==1 && $0=="---" {inhead=1; next} inhead && /^---[[:space:]]*$/ {inhead=0; next} !inhead' "${rule_file}" \
           | grep -ohE '\.claude/(knowledge|skills)/[^[:space:]`"'"'"',;)]+' \
           | sed -E 's/[.,;:)]+$//' | grep -v '[*?]' | sort -u)
done

# --- 8. Заявленное число случаев ↔ фактическое ------------------------------
# Класс, случившийся трижды за один MR: набор растёт, число в документации нет.
claude_md="${CLAUDE_DIR}/CLAUDE.md"

# Набор живёт либо у ядра (`hooks/`), либо у плагина (`plugins/*/scripts/`).
# Искать только в первом месте значит не сверять числа плагинов ВОВСЕ — и
# промолчать об этом: заявленное «25 случаев» осталось бы мнением автора.
suite_path() {  # $1 = имя файла набора → путь или пусто
  local candidate
  candidate="${CLAUDE_DIR}/hooks/$1"
  [ -f "${candidate}" ] && { printf '%s' "${candidate}"; return 0; }
  for candidate in "${CLAUDE_DIR}"/../plugins/*/scripts/"$1"; do
    [ -f "${candidate}" ] && { printf '%s' "${candidate}"; return 0; }
  done
  return 0
}

# Ядро рассказывает и о плагинах — их приборы и наборы описаны здесь же. Но в
# копии потребителя плагинов может не быть: они ставятся отдельно и живут вне
# `.claude/`. Требовать их файлы значит объявлять исправную копию неработоспособной.
# Замер: чистая установка ядра без плагинов дала «КОПИЯ НЕ РАБОТОСПОСОБНА (2)» —
# оба пункта про `check-scenario-coverage.test.sh`, который приезжает с `product-loop`.
#
# Признак принадлежности — не имя и не место упоминания, а СВОЙ ПРИБОР рядом:
# у набора ядра он лежит в `hooks/`. Потерянный набор ядра прибор переживёт и
# останется находкой; отсутствующий плагин не оставляет ни того, ни другого.
suite_is_core() {  # $1 = имя файла набора
  [ -f "${CLAUDE_DIR}/hooks/${1%.test.sh}.sh" ]
}
if [ -f "${claude_md}" ]; then
  while IFS='|' read -r suite claimed; do
    [ -n "${suite}" ] || continue
    checked=$((checked + 1))
    path=$(suite_path "${suite}")
    if [ -z "${path}" ] && ! suite_is_core "${suite}"; then
      # Инструмент со стороны, в этой копии не установлен — не предмет ядра.
      checked=$((checked - 1))
      continue
    fi
    actual=$(grep -m1 '^EXPECTED_CASES=' "${path}" 2>/dev/null | cut -d= -f2)
    if [ -z "${actual}" ]; then
      note "в документации назван набор ${suite}, а файла или его счётчика нет"
    elif [ "${actual}" != "${claimed}" ]; then
      note "${suite}: документация говорит ${claimed} случаев, в наборе ${actual}"
    fi
  done < <(grep -oE '`[a-z-]+\.test\.sh` \([0-9]+ случа' "${claude_md}" \
           | sed -E 's/`([a-z-]+\.test\.sh)` \(([0-9]+) случа/\1|\2/')

  # Числа МУТАЦИЙ доказательством не являются — их нельзя пересчитать прогоном.
  # Но расходиться с записью автора они не должны: класс «набор вырос, число
  # в документации нет» случился трижды за один MR именно на числах случаев.
  # Поэтому набор объявляет `MUTATIONS=` рядом с `EXPECTED_CASES=`, а здесь сверяется.
  while IFS='|' read -r suite claimed_m; do
    [ -n "${suite}" ] || continue
    checked=$((checked + 1))
    path=$(suite_path "${suite}")
    if [ -z "${path}" ] && ! suite_is_core "${suite}"; then
      checked=$((checked - 1))
      continue
    fi
    actual_m=$(grep -m1 '^MUTATIONS=' "${path}" 2>/dev/null | cut -d= -f2 | tr -cd '0-9')
    if [ -z "${actual_m}" ]; then
      note "набор ${suite} не объявляет MUTATIONS, а документация называет число"
    elif [ "${actual_m}" != "${claimed_m}" ]; then
      note "${suite}: документация говорит ${claimed_m} мутаций, в наборе объявлено ${actual_m}"
    fi
  done < <(
    # Без awk: линт CI запрещает трёхаргументный match(), а regex с запятой внутри
    # ловится и двухаргументный — прибор не должен спотыкаться о собственный линт.
    grep -oE '`[a-z-]+\.test\.sh` \([0-9]+ [^,]+, [^ ]+ мутаци' "${claude_md}" 2>/dev/null \
    | while IFS= read -r chunk; do
        suite=$(printf '%s' "${chunk}" | sed -E 's/^`([a-z-]+\.test\.sh)`.*/\1/')
        # `[а-я]` зависит от локали: в `C` GNU трактует класс побайтово и
        # захватывает лишнее. Берём «слово между запятой и словом мутаци» через
        # отрицание ASCII-символов — оно байтово-безопасно в любой локали.
        word=$(printf '%s' "${chunk}" | sed -E 's/.*, ([^ ]+) мутаци.*/\1/')
        num=$(word_to_number "${word}")
        [ "${num}" -gt 0 ] && printf '%s|%s\n' "${suite}" "${num}"
      done
  )
fi

# --- 9. Сущности, названные в CLAUDE.md, определены в словаре ----------------
# Класс: короткая таблица признаков живёт в CLAUDE.md (она всегда в контексте),
# полные определения — в knowledge/entities.md. Два описания одного предмета
# расходятся молча, и роль начинает применять признак, которого больше нет.
entities="${CLAUDE_DIR}/knowledge/entities.md"
if grep -q '^## Сущности' "${claude_md}" 2>/dev/null; then
  checked=$((checked + 1))
  if [ ! -f "${entities}" ]; then
    note "CLAUDE.md объявляет раздел «Сущности», а knowledge/entities.md нет"
  else
    named=0
    # Имена берём из ПЕРВОЙ колонки таблицы признаков и только из неё: жирное
    # начертание в тексте раздела сущностью не является.
    while IFS= read -r term; do
      [ -n "${term}" ] || continue
      named=$((named + 1))
      grep -qE "^## ${term}\$" "${entities}" \
        || note "сущность «${term}» названа в CLAUDE.md, а раздела «## ${term}» в entities.md нет"
    done < <(awk '/^## Сущности/{t=1; next} t && /^## /{t=0} t && /^\| \*\*/ {print}' "${claude_md}" \
             | sed -E 's/^\| \*\*([^*]+)\*\*.*/\1/')
    # Половина «найдено не ноль»: раздел есть, а сущностей в нём ноль — это
    # съехавшая разметка таблицы, а не отсутствие сущностей.
    [ "${named}" -gt 0 ] || note "раздел «Сущности» в CLAUDE.md есть, а ни одной сущности в таблице не разобрано"
  fi
fi

# --- 10. Одна спецификация блока памяти на файл роли -------------------------
# Класс, найденный в пяти файлах ролей сразу: рядом лежали ДВА описания одного
# блока, и второе просило «Что сделано» — то есть ровно хронику, которую первое
# запрещает и которую блокирует memory-gate. Роль получала противоречие в одном
# файле. Заодно ловим непарное ограждение кода: у устаревшего блока оставалась
# висячая ``` и разметка ниже читалась как код.
#
# Шаблон opt-in роли смотрится наравне с файлом активной роли: он и есть будущий
# файл роли, копируется в `agents/` дословно, и дефект в нём проявится не здесь,
# а у потребителя на первом же прогоне после подключения роли. Замер (отчёт с
# мест по 5.3.1): пять шаблонов `optional/` держали внешний заголовок раздела
# дословно равным имени блока внутри ограждения — итого два описания, — и
# подключение ЛЮБОЙ opt-in роли давало «КОПИЯ НЕ РАБОТОСПОСОБНА». В самой
# поставке это было невидимо: проверка смотрела только `agents/`.
specs=0
for role_dir in "${CLAUDE_DIR}/agents" "${CLAUDE_DIR}/templates/roles/optional"; do
  [ -d "${role_dir}" ] || continue
  for role_file in "${role_dir}"/*.md; do
    [ -f "${role_file}" ] || continue
    checked=$((checked + 1))
    blocks=$(grep -c '^## Для памяти роли' "${role_file}" || true)
    specs=$((specs + blocks))
    [ "${blocks}" -le 1 ] \
      || note "$(basename "${role_file}"): описаний блока памяти ${blocks} — роль получает противоречие в одном файле"
    fences=$(grep -c '^```' "${role_file}" || true)
    [ $((fences % 2)) -eq 0 ] \
      || note "$(basename "${role_file}"): непарное ограждение кода (${fences}) — разметка ниже читается как код"
  done
done
# Половина «найдено не ноль»: файлы ролей есть, а спецификации блока памяти нет
# ни в одном — значит память ролей не пополнится, и заметить это будет нечем.
if [ -d "${CLAUDE_DIR}/agents" ] && [ "${specs}" -eq 0 ]; then
  note "файлы ролей есть, а описания блока «Для памяти роли» нет ни в одном"
fi

# --- 11. Роль без блока памяти встаёт на хуке, и причина не видна из файла ----
# Проверка выше ловит ДУБЛЬ («ровно одно описание»), потому что написана против
# замера, который тогда встретился: в пяти файлах лежало по два описания. Ноль
# описаний она пропускает — и именно ноль оказался дороже.
#
# Замер (прогон 5.3.0 на чистой копии, 2026-08-30): блок есть у 6 ядровых ролей
# из 6 и у 0 опциональных из 5. `subagent-arrival.sh` требует раздел «Для памяти
# роли» в отчёте ЛЮБОЙ роли, у которой есть файл в `agents/`, — значит любая
# opt-in роль встаёт на первой же активации, а причина в её файле не названа:
# роль не просит того, чего требует хук.
#
# Шаблоны опциональных ролей смотрятся наравне с `agents/`: они и есть будущие
# файлы ролей, копируются туда дословно, и дрейф между двумя каталогами — тот же
# класс E («построено, но не поставляется»), только внутри самой поставки.
#
# Facilitator исключён по существу: он идёт основной сессией, под `SubagentStop`
# не попадает и блок не выдаёт. Это записано в CLAUDE.md и проверено на нём же —
# у него ноль заголовков блока, и это правильно.
for role_dir in "${CLAUDE_DIR}/agents" "${CLAUDE_DIR}/templates/roles/optional"; do
  [ -d "${role_dir}" ] || continue
  for role_file in "${role_dir}"/*.md; do
    [ -f "${role_file}" ] || continue
    name=$(basename "${role_file}" .md)
    [ "${name}" = "facilitator" ] && continue
    checked=$((checked + 1))
    if [ "$(grep -c '^## Для памяти роли' "${role_file}" || true)" -eq 0 ]; then
      note "${name}: нет описания блока «Для памяти роли» — хук не отпустит роль, а из её файла это не видно"
    fi
  done
done

# --- 12. Маршрут ведёт к роли, которая есть ----------------------------------
# Протоколы маршрутизируют tension по домену: «Рисковая → Guardian», «Чёрная →
# Guardian». Имя роли, которой в копии нет, маршрутом не является — tension уходит
# в никуда и возвращается неразобранным. Замер: три роли боевого проекта (Growth,
# Brand, CFO) переехали в общие протоколы вместе с текстом и остались там после
# того, как состав ролей фреймворка устоялся на одиннадцати.
#
# Смотрим только адресатов маршрутов: правый столбец таблицы шляп и хвост строки
# после `→`. Проза и примеры чужих команд (`guide-multi-agent-teams.md` описывает,
# как собрать СВОЮ команду) под правило не подпадают.
protocols="${CLAUDE_DIR}/knowledge/core-protocols.md"
if [ -f "${protocols}" ]; then
  known=$(
    { ls "${CLAUDE_DIR}"/agents/*.md 2>/dev/null
      ls "${CLAUDE_DIR}"/templates/roles/optional/*.md 2>/dev/null
    } | while IFS= read -r f; do basename "${f}" .md; done | tr 'A-Z' 'a-z'
  )
  # Адресат берётся СТРУКТУРНО: из таблицы, чей заголовок называет исполнителя
  # («Кто ведёт», «Роль»). Класс символов вроде `[A-ZА-Я]` здесь пробовали и
  # отвергли — в локали `C` GNU трактует кириллический диапазон побайтово и матчит
  # строчные тоже; прибор переносимости ловит это первым же прогоном.
  #
  # ГРАНИЦА, названная вслух: маршруты, записанные прозой со стрелкой («Рисковая →
  # Guardian»), не проверяются. Стрелка в этих файлах чаще означает не маршрут, а
  # последовательность («Detect → Fix → Guard»), и разбор давал находки на
  # обычных словах. Таблица — единственная форма, где адресат стоит в известном
  # месте; все три роли, найденные в замере, жили именно в ней.
  addressees=$(
    awk -F'|' '
      /^\|/ && (/Кто/ || /Роль/) { col = NF - 1; want = 1; next }
      /^\|[[:space:]:|-]+$/ { next }
      /^\|/ && want { gsub(/^[[:space:]]+|[[:space:]]+$/, "", $col); print $col; next }
      !/^\|/ { want = 0 }
    ' "${protocols}" \
      | tr '/+' '\n' \
      | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//; s/[(),.]//g' \
      | tr 'A-Z' 'a-z' | sort -u
  )
  while IFS= read -r who; do
    [ -n "${who}" ] || continue
    case "${who}" in ''|fix|guard|prove|document) continue ;; esac
    checked=$((checked + 1))
    grep -qxF "${who}" <<< "${known}" \
      || note "core-protocols.md: маршрут ведёт к роли «${who}», которой в копии нет — tension уйдёт в никуда"
  done <<< "${addressees}"
fi

# --- 13. Бриф не заказывает хронику ------------------------------------------
# Тот же предмет с другой стороны. Проверка выше смотрит файлы ролей, а в момент
# работы сильнее файла роли оказывается БРИФ: он и есть сообщение агенту. Замер:
# форма брифа просила «Для памяти роли: дата, что сделано, решения, следующий шаг»,
# то есть ровно ленту, которую гейт 12 запрещает, `memory-gate.sh` блокирует, а
# канон блока в файле роли заменяет срезом состояния. Правило действовало в одном
# месте из двух, и то, что доезжает до роли, было вторым.
brief="${CLAUDE_DIR}/templates/dispatch-brief.md"
if [ -f "${brief}" ]; then
  checked=$((checked + 1))
  # Смотрим ТОЛЬКО форму — текст внутри ограждения кода, который копируется в
  # сообщение агенту. Проза ниже разбирает этот самый дефект и цитирует его;
  # прибор, ищущий по всему файлу, находил бы собственное объяснение. Класс уже
  # известен: детектор непереносимых форм тоже находил сам себя, пока образец не
  # стали собирать на лету.
  form=$(awk '/^```$/ {inside = !inside; next} inside {print}' "${brief}")
  # Отрицание — не требование. Строка «Не «что сделано за сессию»» ЗАПРЕЩАЕТ хронику,
  # и прибор, ищущий подстроку, принимал запрет за заказ. Ищем строки с «что сделано»,
  # у которых нет отрицания перед ним. Между «не» и оборотом стоит `.*`, а не `.`:
  # точка матчит ОДИН БАЙТ, а кавычка-ёлочка в UTF-8 занимает два — в локали `C`
  # (умолчание CI) сравнение разъезжалось, и запрет снова читался как заказ.
  if grep -q 'Для памяти роли' <<< "${form}" \
     && grep 'что сделано' <<< "${form}" | grep -qv 'Не .*что сделано\|не .*что сделано'; then
    note "dispatch-brief.md: форма брифа заказывает хронику («что сделано») там, где канон роли требует срез состояния"
  fi
  # Гейт 5 применяется ровно здесь: бриф — единственное место, где модель называется.
  checked=$((checked + 1))
  grep -qi 'МОДЕЛЬ\.' <<< "${form}" \
    || note "dispatch-brief.md: в форме брифа нет поля модели — гейт «явный выбор модели» негде исполнить"
fi

# --- 14. Каждый прибор объявляет свой тир ------------------------------------
# Класс: 19 приборов и одно слово «ОБЯЗАТЕЛЬНО» на всех — внимание уходит к самой
# громкой находке, а не к самой дорогой. Тир объявляется строкой `# ТИР:` в самом
# приборе; прибор без тира в сводку `check-findings-budget.sh` не попадает, то есть
# его находки исчезают из порядка молча.
tiered=0
if [ -d "${CLAUDE_DIR}/hooks" ]; then
  for tool in "${CLAUDE_DIR}"/hooks/*.sh; do
    # Наборы проверок и библиотеки приборами не являются: у первых предмет —
    # доказательство, у вторых — общий код, и тира ни у тех, ни у других нет.
    case "$(basename "${tool}")" in *.test.sh|lib-*.sh) continue ;; esac
    [ -f "${tool}" ] || continue
    checked=$((checked + 1))
    declared=$(grep -m1 '^# ТИР:' "${tool}" | sed -E 's/^# ТИР:[[:space:]]*//; s/[[:space:]]*—.*$//')
    if [ -z "${declared}" ]; then
      note "$(basename "${tool}"): тир не объявлен — находки выпадут из сводки молча; если это остаток прежней версии (наложение не удаляет), файл надо убрать"
    else
      tiered=$((tiered + 1))
      case "${declared}" in
        стоп|счёт|копия|волна|показ|сводка) ;;
        *) note "$(basename "${tool}"): тир «${declared}» не из набора (стоп/счёт/копия/волна/показ/сводка)" ;;
      esac
    fi
  done
  # Половина «найдено не ноль»: приборы есть, а тир не объявлен ни у одного —
  # значит сводка пуста, и порядок по ставке не работает вовсе.
  if [ "${tiered}" -eq 0 ]; then
    note "приборы есть, а тир не объявлен ни у одного — сводка находок пуста"
  fi
fi

# --- 15. Таблица ролей ↔ File Ownership файла роли ---------------------------
# Таблица «Роли = Subagents» в CLAUDE.md заведена как быстрая справка, и читают её
# чаще, чем сами файлы ролей. Две записи об одном предмете расходятся молча: замер
# (отчёт с мест по 5.3.1) — таблица давала `cto` зону записи `decisions/DEC-*.md`
# без оговорки, тогда как по механике Decider Protocol `Write` делает facilitator,
# и в самой таблице File Ownership выглядел нарушенным.
#
# Сверяем только то, что сверяемо без догадок: имена файлов. Записи-каталоги
# (`decisions/`), маски (`FEAT-*`, `DEC-NNN`) и проза («документация») пропускаются —
# их форма в двух местах законно разная, и требовать совпадения значило бы
# заставить таблицу повторять раскладку дословно.
claude_md_roles="${CLAUDE_DIR}/CLAUDE.md"
if [ -f "${claude_md_roles}" ]; then
  rows=0
  while IFS='|' read -r _ role_cell _ _ writes _; do
    name=$(printf '%s' "${role_cell}" | sed -E 's/\*//g; s/\(default\)//; s/[[:space:]]//g')
    [ -n "${name}" ] || continue
    # Строка без колонки «Пишет» (таблица opt-in ролей — три колонки) сверять нечего.
    # Считать её осмотренной значило бы набивать `checked` вхолостую.
    [ -n "${writes}" ] || continue
    role_file="${CLAUDE_DIR}/agents/${name}.md"
    [ -f "${role_file}" ] || role_file="${CLAUDE_DIR}/templates/roles/optional/${name}.md"
    [ -f "${role_file}" ] || continue
    grep -q '^## File Ownership' "${role_file}" || continue
    rows=$((rows + 1))
    checked=$((checked + 1))
    own=$(awk '/^## File Ownership/ { inside = 1; next } inside && /^## / { exit } inside' "${role_file}")
    while IFS= read -r pth; do
      [ -n "${pth}" ] || continue
      case "${pth}" in
        */) continue ;;                     # каталог, а не файл
        *'*'*|*NNN*|*NN.*) continue ;;      # маска: форма записи в двух местах законно разная
        *.md|*.txt) ;;
        *) continue ;;                      # проза и куски кода путём не являются
      esac
      mentions_path "${own}" "${pth}" \
        || note "CLAUDE.md: таблица ролей обещает ${name} запись в ${pth}, а File Ownership его файла этого пути не содержит"
    done <<< "$(printf '%s' "${writes}" | grep -oE '`[A-Za-z0-9_/*.-]+`' | tr -d '`')"
  done < <(grep -E '^\| \*\*[a-z]+\*\*' "${claude_md_roles}")
  # Половина «найдено не ноль», применённая к самому разбору: таблица ролей в файле
  # есть, а разобрать из неё не удалось ни строки. Замер ревью 5.3.2: снять `**`
  # вокруг имени роли (обычная работа markdown-форматтера) — и проверка молчит,
  # не отличаясь от исправной копии ничем.
  if grep -q 'Роли = Subagents' "${claude_md_roles}" && [ "${rows}" -eq 0 ]; then
    note "CLAUDE.md: таблица «Роли = Subagents» есть, а разобрано ноль строк — формат таблицы съехал, и сверка владения молча не работает"
  fi
fi

# --- 16. Роль не предписывает себе запись мимо своего File Ownership ---------
# Класс, которого прежде не видел ни один прибор: расхождение ВНУТРИ одного файла.
# Приборы целостности сверяют файл с файлом, а здесь роль спорит сама с собой.
# Замер (отчёт с мест по 5.3.1): `facilitator.md` в функциях 0 и 7 предписывал себе
# «idea → backlog.md; fact → domain.md; term → glossary.md», а собственный раздел
# File Ownership этих путей не содержал, и таблица ролей в CLAUDE.md закрепляла
# `glossary.md`/`domain.md` за `keeper`. Роль получала выбор из двух запрещённых:
# писать без мандата или потерять вход на полпути триажа — при том, что тот же
# файл называет потерянный вход её процессной ошибкой. Слова «передай keeper-у»
# в тексте не было вовсе.
#
# Признак, названный в том же отчёте: грамматика самоупоминания — роль говорит о
# себе маршрутом «→ `файл`», а файла нет в её File Ownership. Смотрим только пути
# ПРОЕКТА: голое имя артефакта (`domain.md`) или путь от `project/`. Справочник
# ремесла (`references/security.md`) роль читает, а не пишет — замер: без этой
# границы прибор давал две находки на чтении OWASP-справочника.
for role_dir in "${CLAUDE_DIR}/agents" "${CLAUDE_DIR}/templates/roles/optional"; do
  [ -d "${role_dir}" ] || continue
  for role_file in "${role_dir}"/*.md; do
    [ -f "${role_file}" ] || continue
    grep -q '^## File Ownership' "${role_file}" || continue
    checked=$((checked + 1))
    own=$(awk '/^## File Ownership/ { inside = 1; next } inside && /^## / { exit } inside' "${role_file}")
    body=$(awk '/^## File Ownership/ { exit } { print }' "${role_file}")
    while IFS= read -r target; do
      [ -n "${target}" ] || continue
      case "${target}" in
        project/*) ;;                       # путь проекта — предмет правила
        */*) continue ;;                    # чужая раскладка: навык, плагин, справочник
      esac
      case "${target}" in *'<'*|*'>'*) continue ;; esac
      mentions_path "${own}" "${target}" \
        || note "$(basename "${role_file}"): предписывает себе «→ ${target}», а этого пути нет в её File Ownership — роль спорит сама с собой"
    done <<< "$(printf '%s' "${body}" | grep -oE '→ *`[A-Za-z0-9_/.-]+\.md`' | tr -d '`' | sed 's/→ *//' | sort -u)"
  done
done

# --- 17. Состав канона не пересказывается в файле роли ------------------------
# Замер (отчёт с мест по 5.3.1): инлайн-пересказ Code-Change Discipline лежал в
# `architect.md` и `dev.md` слово в слово, называл себя «7 шагов» и перечислял
# ШЕСТЬ — пропущено было звено «поставить идею под сомнение первой», которое сам
# канон называет самым дорогим. Совпадение текстов до буквы означает, что копия
# делалась с копии; число «7» при факте «6» — что копию правили, а дом правила нет.
#
# Две работы над одним предметом «состав алгоритма есть в одном месте».
# (1) Дом сам себе верен: число в заголовке канона ↔ число пунктов под ним.
# (2) Файл роли не открывает перечисление состава: признак — «N шагов:» с
#     двоеточием, то есть начало списка. Проза, называющая число («перечислял
#     шесть»), списком не является и находкой не считается.
canon="${CLAUDE_DIR}/knowledge/code-change-discipline.md"
if [ -f "${canon}" ]; then
  checked=$((checked + 1))
  claimed=$(grep -m1 -oE '^## [0-9]+ шаг' "${canon}" | tr -cd '0-9')
  actual=$(awk '/^## [0-9]+ шаг/ { inside = 1; next } /^## / { inside = 0 } inside && /^[0-9]+\. / { n++ } END { print n + 0 }' "${canon}")
  if [ -n "${claimed}" ] && [ "${claimed}" != "${actual}" ]; then
    note "code-change-discipline.md: заголовок обещает ${claimed} шагов, в разделе ${actual} — расходится сам с собой"
  fi
fi
for role_dir in "${CLAUDE_DIR}/agents" "${CLAUDE_DIR}/templates/roles/optional"; do
  [ -d "${role_dir}" ] || continue
  for role_file in "${role_dir}"/*.md; do
    [ -f "${role_file}" ] || continue
    grep -q 'code-change-discipline\.md' "${role_file}" || continue
    checked=$((checked + 1))
    grep -qE '[0-9]+ шаг(ов|а)?:' "${role_file}" \
      && note "$(basename "${role_file}"): пересказывает состав алгоритма («N шагов: …») — состав живёт в каноне, копия отстанет молча"
  done
done

# --- 18. Владелец артефакта знает, чем владеет --------------------------------
# Замер (отчёт с мест по 5.3.1): `templates/project/requirements.md` и `claims.md`
# несут в шапке `owner: "cto"`, а в `.claude/agents/cto.md` — НОЛЬ упоминаний обоих
# путей. Роль действует по своему промпту, а не по шапке чужого файла, которую
# может никогда не открыть, и артефакт замирает на дате заведения — ровно тот
# сценарий, против которого поле `owner` и заведено. Наш прогон нашёл ещё три
# таких пары: `artifacts/README.md`, `resources.md`, `framework-feedback.md` —
# все три за `facilitator`, и все три в его файле не назывались.
#
# Пара «шаблон ↔ роль» сверяется по `artifact_path:` из шапки шаблона: имя файла
# шаблона местом артефакта не является (`artifacts-readme.md` кладётся в
# `artifacts/README.md`), и угадывать это нечем.
owners=0
if [ -d "${CLAUDE_DIR}/templates/project" ]; then
  for tpl in "${CLAUDE_DIR}"/templates/project/*.md; do
    [ -f "${tpl}" ] || continue
    owner=$(fm_value "${tpl}" owner)
    [ -n "${owner}" ] || continue
    # Владелец назван словами («keeper поддерживает форму») — не роль, пропускаем.
    role_file="${CLAUDE_DIR}/agents/${owner}.md"
    [ -f "${role_file}" ] || role_file="${CLAUDE_DIR}/templates/roles/optional/${owner}.md"
    [ -f "${role_file}" ] || continue
    owners=$((owners + 1))
    checked=$((checked + 1))
    target=$(fm_value "${tpl}" artifact_path)
    if [ -z "${target}" ]; then
      note "$(basename "${tpl}"): объявлен owner «${owner}», а artifact_path не назван — сверить владение не с чем"
      continue
    fi
    # Ищем хвост после `project/`: роль пишет `requirements.md`, а не полный путь.
    mentions_path "$(cat "${role_file}")" "${target#project/}" \
      || note "$(basename "${role_file}"): владеет ${target} по шапке шаблона, а в файле роли этот путь не назван — артефакт замрёт на дате заведения"
  done
fi
# Половина «найдено не ноль»: шаблоны есть, а владельцев-ролей не разобрано ни
# одного — значит проверка прошла по пустому множеству.
if [ -d "${CLAUDE_DIR}/templates/project" ] && [ -d "${CLAUDE_DIR}/agents" ] && [ "${owners}" -eq 0 ]; then
  note "шаблоны есть, а ни один owner не разобран как роль — владение не сверено"
fi

# --- 19. Ценности проекта доезжают до роли, которая их нарушит ----------------
# Замер (отчёт с мест по 5.3.1): `project/values.md` читали ТРИ роли из восьми.
# Не читали — `facilitator`, `architect`, `dev`, `test`, `keeper`, то есть обе
# роли, физически трогающие код, и та, что решает, куда пойдёт работа. Приоритетная
# ценность проекта («данные работодателя не попадают в репозиторий») была объявлена
# и недоставлена ПО КОНСТРУКЦИИ: шаблон ценностей приглашает проект объявить свою
# специфику (раздел 9), а канала до ролей у этой специфики не было.
#
# Смотрим ритуал, а не файл целиком: у `architect` путь стоял в File Ownership
# как «читать можно» — это разрешение, а не шаг активации, и роль его не делает.
rituals=0
for role_dir in "${CLAUDE_DIR}/agents" "${CLAUDE_DIR}/templates/roles/optional"; do
  [ -d "${role_dir}" ] || continue
  for role_file in "${role_dir}"/*.md; do
    [ -f "${role_file}" ] || continue
    ritual=$(awk '/^## Старт/ { inside = 1; next } /^## / { inside = 0 } inside' "${role_file}")
    [ -n "${ritual}" ] || continue
    rituals=$((rituals + 1))
    checked=$((checked + 1))
    grep -q 'values\.md' <<< "${ritual}" \
      || note "$(basename "${role_file}"): ритуал не читает project/values.md — проектная ценность объявлена и не доезжает до роли, которая её нарушит"
  done
done
# Половина «найдено не ноль»: файлы ролей есть, а раздела старта нет ни у одной —
# значит проверять было нечего, и молчание здесь означало бы исправность.
if [ -d "${CLAUDE_DIR}/agents" ] && [ "${rituals}" -eq 0 ]; then
  note "файлы ролей есть, а раздела «Старт …» нет ни в одном — активационного ритуала не существует"
fi

# --- 20. Предписанная команда исполнима при собственных запретах --------------
# Класс дороже всех прочих в этом приборе: не «копия отстала от дома», а два
# предписания фреймворка, которых НЕЛЬЗЯ выполнить оба. Замер (отчёт с мест по
# 5.3.1, чистая установка): Шаг 4 `/setup-project` велел заводить память роли
# копированием шаблона (`cp .claude/templates/… project/…`), а Шаг 5 того же
# файла ставил `permissions.deny` на `.claude/templates/**` — и клиент бракует
# копирование по ИСТОЧНИКУ, хотя записи в шаблон нет. После установки запретов
# обе двери закрыты: `Write` по памяти запрещён, `cp` из шаблонов запрещён,
# и завести память новой роли нечем. На самом setup это невидимо — память
# создаётся ДО Шага 5, прогон зелёный; упирается тот, кто подключит роль позже.
#
# Смотрим ровно исполнимую форму: `cp <путь под запретом> <что-то>`. Подстановка
# в пути (`<role>`) формы не отменяет — человек подставит имя и выполнит; замер
# уже на этой версии: инструкция импланта роли в `/self-service` несла ровно такую
# команду, и прибор её пропускал, пока класс символов не знал угловых скобок.
# Проза, разбирающая этот самый дефект, пишет путь с многоточием
# (`.claude/templates/…`) и под правило не подпадает — иначе прибор находил бы
# собственное объяснение.
#
# `UPGRADING.md` смотрится наравне с командами, хотя лежит вне `.claude/`: по нему
# действует агент у потребителя, и невыполнимая команда там стоит ровно столько же.
# Замер прогона по боевым проектам: Шаг 8d.2 предписывал `cp` из каталога шаблонов —
# ту самую форму, которую этот прибор ловит в командах.
setup_cmd="${CLAUDE_DIR}/commands/setup-project.md"
if [ -f "${setup_cmd}" ]; then
  # Запреты берутся из блока, который сам setup и предписывает записать, а не
  # зашиты сюда: разъехаться нечему, и правка блока сразу меняет проверку.
  denied=$(sed -n '/"deny"/,/\]/p' "${setup_cmd}" \
    | grep -oE '(Write|Edit)\(\.claude/[A-Za-z0-9_./-]+' \
    | sed -E 's/^(Write|Edit)\(//' | sort -u)
  # Половина «найдено не ноль» для самого экстрактора: запреты в файле описаны,
  # а разобрать их не удалось — блок переписан прозой или иным форматом. Замер
  # ревью 5.3.2: в таком файле проверка не делала ни одного сравнения и молчала,
  # то есть сертифицировала не «команда исполнима», а «формат не съехал».
  if [ -z "${denied}" ] && grep -q 'deny' "${setup_cmd}"; then
    checked=$((checked + 1))
    note "setup-project.md: запреты названы, а разобрать блок deny не удалось — сверка «предписанное исполнимо» молча не работает"
  fi
  if [ -n "${denied}" ]; then
    while IFS= read -r prefix; do
      [ -n "${prefix}" ] || continue
      checked=$((checked + 1))
      while IFS= read -r hit; do
        [ -n "${hit}" ] || continue
        note "$(basename "${hit}"): предписывает \`cp ${prefix}…\`, а Шаг 5 запрещает этот путь — команду нельзя выполнить после настройки"
      done < <(grep -rlE "cp +${prefix}[A-Za-z0-9_./<>-]+\.[a-z]+ " \
                 "${CLAUDE_DIR}/commands" "${CLAUDE_DIR}/CLAUDE.md" \
                 "${ROOT}/UPGRADING.md" 2>/dev/null)
    done <<< "${denied}"
  fi
fi

printf 'Проверено пунктов: %s. Расхождений: %s.\n' "${checked}" "${#problems[@]}"
[ "${#problems[@]}" -eq 0 ] && exit 0

printf '\nКОПИЯ НЕ РАБОТОСПОСОБНА (%s):\n' "${#problems[@]}" >&2
printf '  %s\n' "${problems[@]}" >&2
exit 1
