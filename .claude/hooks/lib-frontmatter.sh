#!/bin/bash
# Библиотека чтения шапки артефакта. Не прибор и не набор: общий код, который
# подключают проверки строкой `source`. Тира не объявляет — у неё другой предмет,
# и `check-install-integrity.sh` пропускает `lib-*.sh` наравне с наборами.
#
# Предмет один: «значение поля шапки прочитано так, как его написал человек».
#
# Появилась потому, что YAML-комментарий читался как часть значения, а шаблоны
# фреймворка комментарии содержат — и обильно. Замер прогона: решение, заведённое
# из штатного `adr-template.md`, дало две ложных находки подряд. Пустое
# `accepted_until: ""  # ТРЕТИЙ ВИД КРАСНОГО. Заполняется, если…` прибор распада
# счёл заполненным и объявил «ДОЛГ ПРОСРОЧЕН», а заполненное
# `metric_for_revisit: "ставка…"  # обязательно если…` — пустым. Обе находки
# сообщали о дефекте, которого не было, на файле, созданном по инструкции.
#
# Разбор устроен так, а не иначе: значение в кавычках кончается закрывающей
# кавычкой, и решётка внутри кавычек — часть текста («порог #5»). Значение без
# кавычек кончается перед ` #`. Пробел перед решёткой обязателен: `версия#3` —
# одно слово, а не значение с комментарием.
#
# Сломанная библиотека проверку не роняет: вызывающий продолжает работу по
# своему прежнему пути.

# Строки шапки: только первый блок между --- и ---. Та же строка в теле документа
# (цитата, пример, таблица полей) настройкой не является.
fm_lines() {  # $1 = файл
  awk 'NR==1 && $0!="---" {exit} NR==1 {next} /^---[[:space:]]*$/ {exit} {print}' "$1" 2>/dev/null
}

fm_field() {  # $1 = файл, $2 = имя поля → значение без кавычек и без комментария
  fm_lines "$1" \
    | grep -m1 -E "^$2:" \
    | sed -E "s/^$2:[[:space:]]*//" \
    | awk '
        {
          line = $0
          if (substr(line, 1, 1) == "\"" || substr(line, 1, 1) == "\x27") {
            q = substr(line, 1, 1)
            rest = substr(line, 2)
            i = index(rest, q)
            print (i > 0) ? substr(rest, 1, i - 1) : rest
            next
          }
          # Без кавычек: комментарий начинается с « #». Решётка вплотную к тексту
          # комментарием не является.
          i = index(line, " #")
          if (i > 0) line = substr(line, 1, i - 1)
          sub(/[[:space:]]+$/, "", line)
          print line
        }'
}
