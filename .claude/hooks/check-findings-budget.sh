#!/bin/bash
#
# ТИР: сводка — не находит сам, а упорядочивает чужие находки
#
# Требования приборов обозримы и упорядочены по ставке.
#
# Замер (боевой проект, 2026-08-27): 19 приборов, и все девять шагов `/end-session`
# помечены одним словом «ОБЯЗАТЕЛЬНО». Требуют они при этом разного:
#   · артефакты не по домам — **40 предметов**, ставка низкая (файл лежит не там);
#   · пересказы мёртвых решений — 11, ставка средняя;
#   · память ролей — **4**, ставка высшая (`dev` 988 КБ, физически не читается).
# Самая большая куча — самая низкая ставка, и различить нечем. Внимание конечно и
# уходит к самой громкой находке, а не к самой дорогой.
#
# Ирония, ради которой прибор написан: фреймворк изобрёл ПОТОЛОК для реестров
# («выше потолка в реестр перестают смотреть») и не применил его к себе. Полсотни
# предметов за сессию, распределённые по 19 приборам, — тот же переполненный реестр,
# только без реестра.
#
# ЧТО ДЕЛАЕТ. Прогоняет проектные приборы, читает объявленный в каждом ТИР и делит:
#   · **стоп** — ломает следующую сессию либо теряется навсегда. Разбирается сейчас,
#     сначала самое дешёвое из дорогого: порядок по числу предметов ПО ВОЗРАСТАНИЮ;
#   · **счёт** — копится под потолком. Выше потолка перестаёт быть задачей сессии и
#     становится ЦЕЛЬЮ ФАЗЫ: это запись в ledger, а не работа на сегодня.
#
# Тир объявлен строкой `# ТИР:` в самом приборе — единственный источник правды,
# разъехаться нечему. Наличие тира проверяет `check-install-integrity.sh`.
#
# ЗАПУСК: bash .claude/hooks/check-findings-budget.sh   (из корня проекта)
#   exit 0 — стоп-находок нет и счёт в пределах потолка
#   exit 1 — есть стоп-находка, потолок пробит, либо прогонять оказалось нечего
#
# Доказательство мутацией: .claude/hooks/check-findings-budget.test.sh

set -uo pipefail

HOOKS=${HOOKS_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}
LEDGER=${LEDGER_FILE:-project/ledger.md}

# Ёмкость объявляет проект: сколько предметов низкой ставки он готов держать
# открытыми. Свойство проекта, а не фреймворка.
ceiling=$(awk 'NR==1 && $0!="---" {exit} NR==1 {next} /^---[[:space:]]*$/ {exit} {print}' "${LEDGER}" 2>/dev/null \
          | grep -m1 -E '^findings_ceiling:' | sed -E 's/^findings_ceiling:[[:space:]]*//; s/[^0-9].*$//')
case "${ceiling}" in ''|*[!0-9]*) ceiling=${FINDINGS_CEILING:-20} ;; esac

# Считаем предметы работы: число в скобках после заголовка находки, иначе
# сам заголовок — один предмет. Заголовок находки набран заглавными.
# Считаем БЛОКАМИ, а не «строкой, начинающейся с заглавной кириллицы».
# Класс, пойманный первым же прогоном CI: кириллический класс `[А-ЯЁ]` зависит от
# локали. В UTF-8 он работает; в локали `C` (умолчание CI) GNU grep трактует его
# как набор БАЙТОВ — и `[А-ЯЁ]` начинает матчить СТРОЧНЫЕ кириллические тоже,
# потому что у них тот же ведущий байт 0xD0. Прибор считал служебные строки
# находками. Ни shellcheck, ни прежний линт этого не видят.
#
# Структура надёжнее классов: каждая находка отделена пустой строкой (все приборы
# печатают её через `printf '\n...'`), поэтому блок = находка. Число предметов —
# из `(N)` в блоке, иначе один. Внутри только ASCII-классы.
count_items() {  # читает поток находок
  awk 'BEGIN { RS = ""; total = 0 }
       {
         rest = $0; found = 0
         while (match(rest, /\([0-9]+\)/)) {
           total += substr(rest, RSTART + 1, RLENGTH - 2) + 0
           found = 1
           rest = substr(rest, RSTART + RLENGTH)
         }
         if (found == 0) { total += 1 }
       }
       END { print total + 0 }'
}

stop_lines=()
count_lines=()
stop_items=0
count_items_total=0
ran=0

for guard in "${HOOKS}"/check-*.sh; do
  case "$(basename "${guard}")" in
    *.test.sh|check-findings-budget.sh|check-install-integrity.sh|check-version-sync.sh|check-lane-acceptance.sh) continue ;;
  esac
  tier=$(grep -m1 '^# ТИР:' "${guard}" | sed -E 's/^# ТИР:[[:space:]]*//; s/[[:space:]]*—.*$//')
  case "${tier}" in стоп|счёт) ;; *) continue ;; esac

  ran=$((ran + 1))
  findings=$(bash "${guard}" 2>&1 >/dev/null || true)
  [ -n "${findings}" ] || continue
  items=$(printf '%s\n' "${findings}" | count_items)
  [ "${items}" -gt 0 ] || items=1
  name=$(basename "${guard}" .sh)

  if [ "${tier}" = "стоп" ]; then
    stop_lines+=("${items}|${name}")
    stop_items=$((stop_items + items))
  else
    count_lines+=("${items}|${name}")
    count_items_total=$((count_items_total + items))
  fi
done

# Половина «найдено не ноль»: приборов ноль — это отказ разбора, а не здоровый проект.
if [ "${ran}" -eq 0 ]; then
  printf 'ОШИБКА: ни один проектный прибор не найден в %s — сводить нечего.\n' "${HOOKS}" >&2
  printf 'Тир объявляется строкой `# ТИР:` в самом приборе; без него прибор в сводку не входит.\n' >&2
  exit 1
fi

printf 'Сводка находок: прогнано приборов %s, потолок счёта %s.\n' "${ran}" "${ceiling}"

failed=0

if [ ${#stop_lines[@]} -gt 0 ]; then
  {
    printf '\nСТОП — разбирается сейчас (%s предметов). Порядок: дешёвое из дорогого первым.\n' "${stop_items}"
    printf '%s\n' "${stop_lines[@]}" | sort -n | while IFS='|' read -r n g; do
      printf '  %-28s предметов: %s\n' "${g}" "${n}"
    done
    printf 'Каждый из них ломает следующую сессию либо теряет что-то безвозвратно —\n'
    printf 'смотри «ТИР» в шапке прибора, там сказано, что именно.\n'
  } >&2
  failed=1
fi

if [ ${#count_lines[@]} -gt 0 ]; then
  printf '\nСЧЁТ — копится под потолком (%s из %s):\n' "${count_items_total}" "${ceiling}"
  printf '%s\n' "${count_lines[@]}" | sort -rn | while IFS='|' read -r n g; do
    printf '  %-28s предметов: %s\n' "${g}" "${n}"
  done
fi

if [ "${count_items_total}" -gt "${ceiling}" ]; then
  {
    printf '\nПОТОЛОК СЧЁТА ПРОБИТ: %s предметов при ёмкости %s.\n' "${count_items_total}" "${ceiling}"
    printf 'Это больше не задача сессии. Одно из трёх, явно:\n'
    printf '  1) цель фазы меняется на «свести счёт до потолка» и пишется в `ledger.md`;\n'
    printf '  2) часть находок закрывается решением «не чиним» — с причиной, а не молчанием;\n'
    printf '  3) `findings_ceiling:` поднимается в шапке ledger — осознанно и с причиной.\n'
    printf 'Замер: реестр, доросший до 76 открытых записей, перестали открывать вовсе.\n'
  } >&2
  failed=1
fi

[ "${failed}" -eq 0 ] || exit 1
printf 'Стоп-находок нет, счёт в пределах потолка.\n'
exit 0
